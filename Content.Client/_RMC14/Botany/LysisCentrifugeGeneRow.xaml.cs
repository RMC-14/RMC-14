using Content.Client._RMC14.UserInterface;
using Content.Client.Resources;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._RMC14.Botany;

[GenerateTypedNameReferences]
public sealed partial class LysisCentrifugeGeneRow : PanelContainer
{
    private static readonly Color AlternateRowColor = Color.Black.WithAlpha(0.2f);

    public LysisCentrifugeGeneRow()
    {
        RobustXamlLoader.Load(this);
        GeneLabel.FontOverride = IoCManager.Resolve<IResourceCache>().GetFont("/Fonts/NotoSans/NotoSans-Bold.ttf", 12);
        ExtractButton.SetIcon(RMCIcons.FloppyDisk);
    }

    public void SetGene(int index, string code, string name, string tooltip, string? extractTooltip)
    {
        PanelOverride = new StyleBoxFlat { BackgroundColor = index % 2 == 0 ? AlternateRowColor : Color.Transparent };
        CodeLabel.Text = code;
        GeneLabel.Text = name;
        GeneLabel.ToolTip = tooltip;
        ExtractButton.ToolTip = extractTooltip;
    }
}
