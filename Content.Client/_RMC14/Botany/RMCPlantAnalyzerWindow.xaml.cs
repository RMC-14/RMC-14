using Content.Client.UserInterface.Controls;
using Content.Shared._RMC14.Botany;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._RMC14.Botany;

[GenerateTypedNameReferences]
public sealed partial class RMCPlantAnalyzerWindow : FancyWindow
{
    public RMCPlantAnalyzerWindow()
    {
        RobustXamlLoader.Load(this);

        BotanyUiStyle.Header(TraitsHeader);
        BotanyUiStyle.Header(NotesHeader);
        BotanyUiStyle.Header(VitalsHeader);
        BotanyUiStyle.Header(ConditionsHeader);
        BotanyUiStyle.Header(TrayHeader);
        BotanyUiStyle.Header(ChemicalsHeader);

        HealthMetric.SetAccentColor(BotanyUiStyle.MetricHealthColor);
        GrowthMetric.SetAccentColor(BotanyUiStyle.MetricGrowthColor);
        TemperatureMetric.SetAccentColor(BotanyUiStyle.MetricTemperatureColor);
        PressureMetric.SetAccentColor(BotanyUiStyle.MetricPressureColor);
        WaterMetric.SetAccentColor(BotanyUiStyle.MetricWaterColor);
        NutritionMetric.SetAccentColor(BotanyUiStyle.MetricNutrientsColor);
        PestMetric.SetAccentColor(BotanyUiStyle.MetricPestsColor);
        WeedMetric.SetAccentColor(BotanyUiStyle.MetricWeedsColor);
        ToxinMetric.SetAccentColor(BotanyUiStyle.MetricToxinsColor);
    }

    public void SetStatus(string text, Color color)
    {
        BotanyUiStyle.StatusRow(TargetStatusPanel, TargetStatusLabel, text, color);
    }

    public void SetTraitRows(IEnumerable<(string Name, string Value)> rows)
    {
        BotanyUiStyle.SetStatRows(TraitsGrid, rows);
    }

    public void SetNotes(IEnumerable<string> notes)
    {
        NotesContainer.DisposeAllChildren();
        foreach (var note in notes)
        {
            var label = new RichTextLabel();
            label.SetMessage(note);
            NotesContainer.AddChild(label);
        }
    }

    public void SetChemicals(IEnumerable<RMCPlantAnalyzerChemical> chemicals)
    {
        ChemicalsContainer.DisposeAllChildren();
        var rowIndex = 0;
        foreach (var chem in chemicals)
        {
            var row = new RMCPlantAnalyzerChemicalRow();
            row.SetChemical(chem, rowIndex++);
            ChemicalsContainer.AddChild(row);
        }
    }
}
