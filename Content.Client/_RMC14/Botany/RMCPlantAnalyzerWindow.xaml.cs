using Content.Client._RMC14.UserInterface;
using Content.Client.Resources;
using Content.Shared._RMC14.Botany;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._RMC14.Botany;

[GenerateTypedNameReferences]
public sealed partial class RMCPlantAnalyzerWindow : DefaultWindow
{
    private static readonly Color BarBackgroundColor = Color.FromHex("#3A3F45");
    private static readonly Color WindowBackgroundColor = Color.FromHex("#16181B");

    public RMCPlantAnalyzerWindow()
    {
        RobustXamlLoader.Load(this);
        RMCMachineUiStyle.RemoveWindowBorder(this, WindowBackgroundColor);

        StatusBannerLabel.FontOverride = IoCManager.Resolve<IResourceCache>().GetFont("/Fonts/NotoSans/NotoSans-Bold.ttf", 12);
        HealthBar.BackgroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = BarBackgroundColor };
        GrowthBar.BackgroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = BarBackgroundColor };
    }

    public void SetStatus(string status, string detail, Color color)
    {
        StatusBanner.PanelOverride = new StyleBoxFlat { BackgroundColor = color };
        StatusBannerLabel.Text = status;
        StatusBannerDetail.Text = detail;
    }

    public void SetHealth(float ratio, string text, Color color)
    {
        SetBar(HealthBar, HealthBarText, ratio, text, color);
    }

    public void SetGrowth(float ratio, string text, Color color)
    {
        SetBar(GrowthBar, GrowthBarText, ratio, text, color);
    }

    public void SetStatChips(IEnumerable<(string Name, string Value, Color Color)> chips)
    {
        StatChips.DisposeAllChildren();
        foreach (var (name, value, color) in chips)
        {
            var chip = new RMCBotanyStatChip();
            chip.SetStat(name, value, color);
            StatChips.AddChild(chip);
        }
    }

    public void SetTrayRows(IEnumerable<(string Name, string Value, Color Color)> rows)
    {
        SetInfoRows(TrayRows, rows);
    }

    public void SetTraitRows(IEnumerable<(string Name, string Value, Color Color)> rows)
    {
        SetInfoRows(TraitRows, rows);
    }

    public void SetChemicals(IEnumerable<RMCPlantAnalyzerChemical> chemicals)
    {
        ChemicalsContainer.DisposeAllChildren();
        foreach (var chem in chemicals)
        {
            var row = new RMCPlantAnalyzerChemicalRow();
            row.SetChemical(chem);
            ChemicalsContainer.AddChild(row);
        }
    }

    public void SetNotes(IEnumerable<string> notes)
    {
        NotesContainer.DisposeAllChildren();
        foreach (var note in notes)
        {
            var row = new RMCBotanyNoteRow();
            row.SetNote(note);
            NotesContainer.AddChild(row);
        }
    }

    private static void SetBar(ProgressBar bar, Label label, float ratio, string text, Color color)
    {
        bar.Value = Math.Clamp(ratio, 0f, 1f);
        bar.ForegroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = color };
        label.Text = text;
    }

    private static void SetInfoRows(BoxContainer container, IEnumerable<(string Name, string Value, Color Color)> rows)
    {
        container.DisposeAllChildren();
        foreach (var (name, value, color) in rows)
        {
            var row = new RMCBotanyInfoRow();
            row.SetInfo(name, value, color);
            container.AddChild(row);
        }
    }
}
