using Content.Client._RMC14.UserInterface;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.Botany;

[GenerateTypedNameReferences]
public sealed partial class GeneEditorWindow : FancyWindow
{
    public GeneEditorWindow()
    {
        RobustXamlLoader.Load(this);

        BotanyUiStyle.Header(DiscHeader);

        BotanyUiStyle.IconButton(ApplyButton, RMCIcons.Radiation, "Apply Genes", BotanyUiStyle.GreenColor, bordered: true, alignment: Control.HAlignment.Left);
        BotanyUiStyle.IconButton(EjectButton, RMCIcons.Eject, "Eject All", BotanyUiStyle.GreenColor, bordered: true, alignment: Control.HAlignment.Left);
    }

    public void SetDiscStatus(string text)
    {
        BotanyUiStyle.StatusRow(DiscStatusPanel, DiscStatusLabel, text, BotanyUiStyle.GreenColor);
    }

    public void ClearDiscStatus()
    {
        BotanyUiStyle.ClearStatusRow(DiscStatusPanel, DiscStatusLabel);
    }

    public void SetDiscGenes(IEnumerable<string> labels)
    {
        DiscGenesContainer.DisposeAllChildren();
        foreach (var label in labels)
        {
            DiscGenesContainer.AddChild(new Label { Text = $"• {label}" });
        }
    }

    public void SetSeedStatus(string text, string? tooltip)
    {
        BotanyUiStyle.StatusRow(SeedStatusPanel, SeedStatusLabel, text, BotanyUiStyle.GreenColor);
        SeedStatusLabel.ToolTip = tooltip;
    }

    public void ClearSeedStatus()
    {
        BotanyUiStyle.ClearStatusRow(SeedStatusPanel, SeedStatusLabel);
        SeedStatusLabel.ToolTip = null;
    }

    public void SetSeedTraitRows(IEnumerable<(string Name, string Value)> rows)
    {
        BotanyUiStyle.SetStatRows(SeedTraitsGrid, rows);
    }
}
