using Content.Client.Resources;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._RMC14.Botany;

[GenerateTypedNameReferences]
public sealed partial class GeneEditorWindow : DefaultWindow
{
    private static readonly Color BarBackgroundColor = Color.FromHex("#3A3F45");
    private static readonly Color MutedColor = Color.FromHex("#8E9AA6");

    public GeneEditorWindow()
    {
        RobustXamlLoader.Load(this);

        SeedBannerLabel.FontOverride = IoCManager.Resolve<IResourceCache>().GetFont("/Fonts/NotoSans/NotoSans-Bold.ttf", 12);
        EditCountBar.BackgroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = BarBackgroundColor };
    }

    public void SetSeedBanner(string status, string detail, Color color)
    {
        SeedBanner.PanelOverride = new StyleBoxFlat { BackgroundColor = color };
        SeedBannerLabel.Text = status;
        SeedBannerDetail.Text = detail;
    }

    public void SetEditCount(float? ratio, string text, Color color)
    {
        EditCountRow.Visible = ratio != null;
        EditCountBar.Value = Math.Clamp(ratio ?? 0f, 0f, 1f);
        EditCountBar.ForegroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = color };
        EditCountBarText.Text = text;
    }

    public void SetSeedChips(IEnumerable<(string Name, string Value, Color Color)> chips)
    {
        SeedChips.DisposeAllChildren();
        foreach (var (name, value, color) in chips)
        {
            var chip = new RMCBotanyStatChip();
            chip.SetStat(name, value, color);
            SeedChips.AddChild(chip);
        }

        SeedChips.Visible = SeedChips.ChildCount > 0;
    }

    public void SetSeedTraitRows(IEnumerable<(string Name, string Value, Color Color)> rows)
    {
        SeedTraitRows.DisposeAllChildren();
        foreach (var (name, value, color) in rows)
        {
            var row = new RMCBotanyInfoRow();
            row.SetInfo(name, value, color);
            SeedTraitRows.AddChild(row);
        }

        SeedTraitsCard.Visible = SeedTraitRows.ChildCount > 0;
    }

    public void SetDisc(bool inserted, string? source, IReadOnlyCollection<string> genes)
    {
        DiscRow.SetInfo("Disc", inserted ? "Inserted" : "None", inserted ? Color.White : MutedColor);

        DiscSourceRow.Visible = inserted && source != null;
        DiscSourceRow.SetInfo("Gene Source", source ?? string.Empty, Color.White);

        NoDiscGenesLabel.Visible = inserted && genes.Count == 0;

        DiscGenesContainer.DisposeAllChildren();
        if (!inserted)
            return;

        foreach (var gene in genes)
        {
            var row = new RMCBotanyNoteRow();
            row.SetNote(gene);
            DiscGenesContainer.AddChild(row);
        }
    }
}
