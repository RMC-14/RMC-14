using Content.Shared._RMC14.Botany;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.Botany;

[GenerateTypedNameReferences]
public sealed partial class RMCPlantAnalyzerChemicalRow : PanelContainer
{
    public RMCPlantAnalyzerChemicalRow()
    {
        RobustXamlLoader.Load(this);
    }

    public void SetChemical(RMCPlantAnalyzerChemical chem, int rowIndex)
    {
        PanelOverride = new StyleBoxFlat { BackgroundColor = BotanyUiStyle.GetRowColor(rowIndex) };
        Marker.PanelOverride = new StyleBoxFlat { BackgroundColor = chem.Color };
        NameLabel.Text = chem.Name;
        AmountLabel.Text = $"{chem.Min}–{chem.Max}u";
    }
}
