using Content.Client._RMC14.UserInterface;
using Content.Client.Resources;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._RMC14.Botany;

[GenerateTypedNameReferences]
public sealed partial class LysisCentrifugeWindow : DefaultWindow
{
    private static readonly StyleBoxFlat ChipStyle = new()
    {
        BackgroundColor = RMCMachineUiStyle.FieldColor,
        BorderColor = RMCMachineUiStyle.ButtonColor,
        BorderThickness = new Thickness(1),
    };

    private readonly Font _bannerFont;

    public LysisCentrifugeWindow()
    {
        RobustXamlLoader.Load(this);
        RMCMachineUiStyle.RemoveWindowBorder(this);

        _bannerFont = IoCManager.Resolve<IResourceCache>().GetFont("/Fonts/NotoSans/NotoSans-Bold.ttf", 12);

        ProcessSeedButton.SetIcon(RMCIcons.Flask);
        EjectSeedButton.SetIcon(RMCIcons.Eject);
        ClearBufferButton.SetIcon(RMCIcons.Trash);
        EjectDiscButton.SetIcon(RMCIcons.Eject);
    }

    public void SetSeedBanner(string status, string detail, Color color)
    {
        RMCMachineUiStyle.Notice(SeedBanner, SeedBannerLabel, status, color, _bannerFont);
        SeedBannerDetail.Text = detail;
        SeedBannerDetail.FontColorOverride = SeedBannerLabel.FontColorOverride;
    }

    public void SetSeedChips(IEnumerable<(string Name, string Value, Color Color)> chips)
    {
        SeedChips.DisposeAllChildren();
        foreach (var (name, value, color) in chips)
        {
            var chip = new RMCBotanyStatChip();
            chip.SetStat(name, value, color);
            chip.PanelOverride = ChipStyle;
            SeedChips.AddChild(chip);
        }

        SeedChips.Visible = SeedChips.ChildCount > 0;
    }

    public void SetSeedTraitRows(IEnumerable<(string Name, string Value, Color Color)> rows)
    {
        SeedTraitRows.DisposeAllChildren();
        foreach (var (name, value, color) in rows)
        {
            var row = new RMCBotanyInfoRow();
            row.SetInfo(name, value, color);
            SeedTraitRows.AddChild(row);
        }

        SeedTraitsCard.Visible = SeedTraitRows.ChildCount > 0;
    }

    public void SetGenome(string? genome, Color color)
    {
        GenomeLabel.Text = genome ?? "None loaded";
        GenomeLabel.FontColorOverride = genome == null ? RMCMachineUiStyle.LabelColor : color;
    }

    public void SetDegradation(float ratio, string text, Color color)
    {
        RMCMachineUiStyle.Bar(DegradationBar, ratio, color);
        DegradationBarText.Text = text;
    }

    public void SetDisc(bool inserted)
    {
        DiscLabel.Text = inserted ? "Inserted" : "None";
        DiscLabel.FontColorOverride = inserted ? Color.White : RMCMachineUiStyle.LabelColor;
    }
}
