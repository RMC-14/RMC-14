using Content.Client._RMC14.UserInterface;
using Content.Client.Resources;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._RMC14.Botany;

[GenerateTypedNameReferences]
public sealed partial class LysisCentrifugeWindow : FancyWindow
{
    public LysisCentrifugeWindow()
    {
        RobustXamlLoader.Load(this);

        var resourceCache = IoCManager.Resolve<IResourceCache>();

        GenomeNameLabel.FontOverride = resourceCache.GetFont("/Fonts/NotoSans/NotoSans-Bold.ttf", 12);

        BotanyUiStyle.Header(GenomeHeader);
        BotanyUiStyle.Header(DiscHeader);
        BotanyUiStyle.Header(GenesHeader);

        BotanyUiStyle.IconButton(EjectSeedButton, RMCIcons.Eject, "Eject Seed", BotanyUiStyle.GreenColor, bordered: true, alignment: Control.HAlignment.Left);
        BotanyUiStyle.IconButton(ProcessSeedButton, RMCIcons.ArrowsRotate, "Process", BotanyUiStyle.GreenColor, bordered: true, alignment: Control.HAlignment.Left);
        BotanyUiStyle.IconButton(ClearBufferButton, RMCIcons.Trash, "Clear Buffer", BotanyUiStyle.GreenColor, bordered: true);
        BotanyUiStyle.IconButton(EjectDiscButton, RMCIcons.Eject, "Eject Disc", BotanyUiStyle.GreenColor, bordered: true, alignment: Control.HAlignment.Left);
    }

    public void SetSeedStatus(string text, string? tooltip)
    {
        BotanyUiStyle.StatusRow(SeedStatusPanel, SeedStatusLabel, text, BotanyUiStyle.GreenColor);
        SeedStatusLabel.ToolTip = tooltip;
    }

    public void ClearSeedStatus()
    {
        BotanyUiStyle.ClearStatusRow(SeedStatusPanel, SeedStatusLabel);
        SeedStatusLabel.ToolTip = null;
    }

    public void SetSeedTraitRows(IEnumerable<(string Name, string Value)> rows)
    {
        BotanyUiStyle.SetStatRows(SeedTraitsGrid, rows);
    }

    public void SetGenomeStatus(string name, Color color)
    {
        BotanyUiStyle.StatusRow(GenomeStatusPanel, GenomeNameLabel, name, color);
    }

    public void ClearGenomeStatus()
    {
        BotanyUiStyle.ClearStatusRow(GenomeStatusPanel, GenomeNameLabel);
    }

    public void SetDiscStatus(string text)
    {
        BotanyUiStyle.StatusRow(DiscStatusPanel, DiscStatusLabel, text, BotanyUiStyle.GreenColor);
    }

    public void ClearDiscStatus()
    {
        BotanyUiStyle.ClearStatusRow(DiscStatusPanel, DiscStatusLabel);
    }
}
