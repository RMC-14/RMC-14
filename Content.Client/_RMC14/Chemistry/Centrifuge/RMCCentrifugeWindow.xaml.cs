using Content.Client._RMC14.UserInterface;
using Content.Client.Resources;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using static Content.Client._RMC14.UserInterface.RMCMachineUiStyle;

namespace Content.Client._RMC14.Chemistry.Centrifuge;

[GenerateTypedNameReferences]
public sealed partial class RMCCentrifugeWindow : DefaultWindow
{
    private readonly RMCIconLabelRow _modeIcon;
    private readonly Label _sourceLabel;
    private readonly Font _bannerFont;

    public RMCCentrifugeWindow()
    {
        RobustXamlLoader.Load(this);
        RemoveWindowBorder(this);

        _bannerFont = RMCMachineUiStyle.BoldFont(IoCManager.Resolve<IResourceCache>());
        LabelEdit.StyleBoxOverride = Field();

        _modeIcon = ModeButton.SetIcon(RMCIcons.ArrowsSplitUpAndLeft, "Mode: split", 16);

        _sourceLabel = SourceButton.SetIcon(RMCIcons.Flask, "Input: Container", 16).Label;

        ConnectButton.SetIcon(RMCIcons.Link, "Connect a Turing Dispenser", 16);

        EjectInputButton.SetIcon(RMCIcons.Eject, "Eject", 16);
        EjectOutputButton.SetIcon(RMCIcons.Eject, "Eject", 16);
    }

    public void SetMode(bool split)
    {
        _modeIcon.Label.Text = split ? "Mode: split" : "Mode: distribute";
        _modeIcon.SetIcon(split ? RMCIcons.ArrowsSplitUpAndLeft : RMCIcons.EqualsSign);
    }

    public void SetSource(string text)
    {
        _sourceLabel.Text = text;
    }

    public void SetConnection(bool connected)
    {
        Notice(ConnectionPanel,
            ConnectionLabel,
            connected ? "Turing Dispenser connected!" : "No Turing Dispenser connected!",
            NoticeInfoColor,
            _bannerFont);
    }

    public void SetLabel(string? label)
    {
        if (LabelEdit.HasKeyboardFocus())
            return;

        LabelEdit.Text = label ?? string.Empty;
    }
}
