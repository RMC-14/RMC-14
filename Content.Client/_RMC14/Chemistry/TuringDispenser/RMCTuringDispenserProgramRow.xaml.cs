using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._RMC14.Chemistry.TuringDispenser;

[GenerateTypedNameReferences]
public sealed partial class RMCTuringDispenserProgramRow : Control
{
    private static readonly ResPath VialsRsi = new("/Textures/_RMC14/Objects/Chemistry/vials.rsi");
    private const int MinFillLevel = 1;
    private const int MaxFillLevel = 6;

    private readonly SpriteSystem _sprite;

    public RMCTuringDispenserProgramRow()
    {
        RobustXamlLoader.Load(this);

        _sprite = IoCManager.Resolve<IEntitySystemManager>().GetEntitySystem<SpriteSystem>();

        VialIcon.Texture = _sprite.Frame0(new SpriteSpecifier.Rsi(VialsRsi, "vial"));
        VialIcon.SetSize = new Vector2(20, 20);

        VialFillIcon.SetSize = new Vector2(20, 20);
        SetFillFraction(1);
    }

    public void SetFillFraction(float fraction)
    {
        var level = Math.Clamp((int) Math.Ceiling(fraction * MaxFillLevel), MinFillLevel, MaxFillLevel);
        VialFillIcon.Texture = _sprite.Frame0(new SpriteSpecifier.Rsi(VialsRsi, $"vial{level}"));
    }
}
