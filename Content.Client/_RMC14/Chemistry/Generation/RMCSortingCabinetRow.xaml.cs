using Content.Client._RMC14.UserInterface;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.Chemistry.Generation;

[GenerateTypedNameReferences]
public sealed partial class RMCSortingCabinetRow : BoxContainer
{
    public RMCSortingCabinetRow()
    {
        RobustXamlLoader.Load(this);

        ExpandButton.Secondary = true;
        TakeOutButton.SetIcon(RMCIcons.Print, string.Empty);
        SetExpanded(false);
    }

    public void SetExpanded(bool expanded)
    {
        ExpandButton.Pressed = expanded;
        ExpandButton.SetIcon(expanded ? RMCIcons.SquareMinus : RMCIcons.SquarePlus, string.Empty);
        Body.Visible = expanded;
    }
}
