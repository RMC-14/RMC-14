using System;
using Content.Client._RMC14.UserInterface;
using Content.Client.Resources;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Maths;
using Robust.Shared.Timing;

namespace Content.Client._RMC14.Chemistry.Generation;

[GenerateTypedNameReferences]
public sealed partial class RMCResearchComputerWindow : DefaultWindow
{
    public static readonly Color AmberBright = Color.FromHex("#FAC000");
    public static readonly Color AmberDim = Color.FromHex("#C69214");
    public static readonly Color AmberBlack = Color.FromHex("#221801");
    public static readonly Color AmberBorder = Color.FromHex("#8A6800");
    public static readonly Color AmberWashed = Color.FromHex("#7A6A2E");

    [Dependency] private readonly IGameTiming _timing = default!;

    public TimeSpan CycleStart;
    public TimeSpan CycleEnd;

    public readonly Label BrokerClearanceLabel;

    private readonly List<RMCResearchTabButton> _tabButtons = new();

    public RMCResearchComputerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var resourceCache = IoCManager.Resolve<IResourceCache>();
        var smallFont = resourceCache.GetFont("/Fonts/NotoSans/NotoSans-Regular.ttf", 8);

        BrokerClearanceLabel = Icon(BrokerClearanceButton, RMCIcons.Gear, "Broker Clearance");
        Icon(ReprintContractButton, RMCIcons.ArrowsRotate, "Reprint");

        HideOldReportsButton.Label.FontColorOverride = AmberBright;
        ContractCooldownLabel.FontOverride = smallFont;

        foreach (var button in new[]
                 {
                     DocumentsSortTimeButton, DocumentsSortCompoundButton,
                     PublishedSortTimeButton, PublishedSortCompoundButton,
                 })
        {
            button.Label.FontColorOverride = AmberBright;
        }

        BuildTabBar();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (CycleEnd <= CycleStart)
        {
            ContractCooldownBar.Value = 0;
            ContractCooldownLabel.Text = string.Empty;
            return;
        }

        var time = _timing.CurTime;
        var remaining = CycleEnd - time;
        if (remaining < TimeSpan.Zero)
            remaining = TimeSpan.Zero;

        ContractCooldownBar.MinValue = (float) CycleStart.TotalSeconds;
        ContractCooldownBar.MaxValue = (float) CycleEnd.TotalSeconds;
        ContractCooldownBar.Value = (float) time.TotalSeconds;
        ContractCooldownLabel.Text = $"Contracts Refresh in: {(int) remaining.TotalSeconds}";
    }

    private void BuildTabBar()
    {
        _tabButtons.Clear();
        TabBar.RemoveAllChildren();

        AddTabButton(RMCIcons.Gear, "Manage", "Research");
        AddTabButton(RMCIcons.Flask, "View", "Chemicals");
        AddTabButton(RMCIcons.Book, "Published", "Material");

        SetActiveTab(Tabs.CurrentTab);
        Tabs.OnTabChanged += SetActiveTab;
    }

    private void AddTabButton(string iconPath, string line1, string line2)
    {
        var index = _tabButtons.Count;
        var tab = new RMCResearchTabButton();
        tab.Setup(iconPath, line1, line2);
        tab.OnPressed += _ => Tabs.CurrentTab = index;
        TabBar.AddChild(tab);
        _tabButtons.Add(tab);
    }

    private void SetActiveTab(int index)
    {
        for (var i = 0; i < _tabButtons.Count; i++)
        {
            _tabButtons[i].SetActive(i == index);
        }
    }

    public static void SetPurchasableStyle(Button button, bool canAfford, Color? disabledColor = null)
    {
        if (button.StyleBoxOverride is not StyleBoxFlat box)
            return;

        box.BackgroundColor = canAfford ? AmberBright : disabledColor ?? Color.Transparent;
    }

    private static Label Icon(Button button, string texturePath, string text)
    {
        var row = button.AddIconLabel(texturePath, text, 16, HAlignment.Stretch);
        row.Margin = new Thickness(10, 0, 6, 0);
        row.SeparationOverride = 8;
        return row.Label;
    }
}
