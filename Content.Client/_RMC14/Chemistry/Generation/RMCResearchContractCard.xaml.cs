using Content.Client._RMC14.UserInterface;
using Content.Client.Resources;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using static Content.Client._RMC14.Chemistry.Generation.RMCResearchComputerWindow;

namespace Content.Client._RMC14.Chemistry.Generation;

[GenerateTypedNameReferences]
public sealed partial class RMCResearchContractCard : BoxContainer
{
    private readonly RMCIconRect _takeIcon;
    private readonly Label _takeButtonLabel;

    public int SlotIndex;
    public Action<int>? OnTake;

    public RMCResearchContractCard()
    {
        RobustXamlLoader.Load(this);

        var resourceCache = IoCManager.Resolve<IResourceCache>();
        var smallFont = resourceCache.GetFont("/Fonts/NotoSans/NotoSans-Regular.ttf", 8);
        var boldFont = resourceCache.GetFont("/Fonts/NotoSans/NotoSans-Bold.ttf", 12);

        RecipeHintLabel.FontOverride = smallFont;
        PropertyHintLabel.FontOverride = smallFont;

        TakeButton.Modulate = Color.White;
        TakeButton.ModulateSelfOverride = Color.White;
        TakeButton.StyleBoxOverride = new StyleBoxFlat
        {
            BackgroundColor = AmberBright,
            BorderColor = AmberBorder,
            BorderThickness = new Thickness(2),
        };

        var takeRow = TakeButton.AddIconLabel(RMCIcons.Print, string.Empty, 28, fontColor: AmberBlack);
        takeRow.SeparationOverride = 8;
        takeRow.Margin = new Thickness(10, 4);
        takeRow.Label.FontOverride = boldFont;
        _takeIcon = takeRow.Icon;
        _takeButtonLabel = takeRow.Label;

        TakeButton.OnPressed += _ => OnTake?.Invoke(SlotIndex);
    }

    public void SetTakeState(bool enabled, string text)
    {
        TakeButton.Disabled = !enabled;
        SetPurchasableStyle(TakeButton, enabled);
        _takeIcon.IdleColor = enabled ? RMCIcons.Idle : RMCIcons.Yellow;
        _takeButtonLabel.FontColorOverride = enabled ? AmberBlack : AmberBright;
        _takeButtonLabel.Text = text;
    }
}
