using Content.Client._RMC14.UserInterface;
using Content.Client.Resources;
using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using static Content.Client._RMC14.UserInterface.RMCMachineUiStyle;

namespace Content.Client._RMC14.Chemistry.Generation;

[GenerateTypedNameReferences]
public sealed partial class RMCSortingCabinetWindow : DefaultWindow
{
    public RMCSortingCabinetWindow()
    {
        RobustXamlLoader.Load(this);
        RemoveWindowBorder(this);

        SearchEdit.StyleBoxOverride = Field();

        var font = IoCManager.Resolve<IResourceCache>().GetFont("/Fonts/NotoSans/NotoSans-Bold.ttf", 12);
        Notice(EmptyPanel, EmptyLabel, "Cabinet is empty!", NoticeInfoColor, font);
    }

    public void SetSortButton(RMCMachineButton button, bool selected)
    {
        button.Accent = selected ? ButtonSelectedColor : ButtonColor;
    }

    public void SetDescending(bool descending)
    {
        OrderButton.SetIcon(descending ? RMCIcons.ArrowDown91 : RMCIcons.ArrowDown19, string.Empty);
        SetSortButton(OrderButton, descending);
    }
}
