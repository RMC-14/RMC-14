using Content.Client._RMC14.UserInterface;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using static Content.Client._RMC14.Chemistry.Generation.RMCResearchComputerWindow;

namespace Content.Client._RMC14.Chemistry.Generation;

[GenerateTypedNameReferences]
public sealed partial class RMCResearchTabButton : Button
{
    private readonly StyleBoxFlat _box = new()
    {
        BackgroundColor = Color.Transparent,
        BorderColor = AmberBorder,
        BorderThickness = new Thickness(4),
    };

    public RMCResearchTabButton()
    {
        RobustXamlLoader.Load(this);

        Modulate = Color.White;
        ModulateSelfOverride = Color.White;
        StyleBoxOverride = _box;
        TabIcon.BindHover(this);

        SetActive(false);
    }

    public void Setup(string iconPath, string line1, string line2)
    {
        TabIcon.SetIcon(iconPath);
        Line1Label.Text = line1;
        Line2Label.Text = line2;
    }

    public void SetActive(bool active)
    {
        TabIcon.IdleColor = active ? RMCIcons.Idle : RMCIcons.Yellow;
        _box.BackgroundColor = active ? AmberBright : Color.Transparent;

        var fontColor = active ? AmberBlack : AmberBright;
        Line1Label.FontColorOverride = fontColor;
        Line2Label.FontColorOverride = fontColor;
    }
}
