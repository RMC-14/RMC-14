namespace Content.Client._RMC14.Chemistry.Generation;

[GenerateTypedNameReferences]
public sealed partial class RMCSynthesisSimulatorWindow : DefaultWindow
{
    private const int CreditsBarMax = 100;
    private const int CreditsGoodThreshold = 60;
    private const int CreditsDefaultThreshold = 40;
    private const int CreditsAverageThreshold = 15;

    private readonly Font _noticeFont;

    public RMCSynthesisSimulatorWindow()
    {
        RobustXamlLoader.Load(this);
        RemoveWindowBorder(this);

        _noticeFont = IoCManager.Resolve<IResourceCache>().GetFont("/Fonts/NotoSans/NotoSans-Bold.ttf", 12);
        CreditsLabel.FontOverride = _noticeFont;

        SimulateButton.SetIcon(RMCIcons.Radiation, "SIMULATE");
        CancelButton.SetIcon(RMCIcons.Stop, "CANCEL");
        CancelButton.Accent = ButtonCautionColor;
        OverrideButton.SetIcon(RMCIcons.Server, "OVERRIDE");
        EjectTargetButton.SetIcon(RMCIcons.Eject, "EJECT TARGET");
        EjectReferenceButton.SetIcon(RMCIcons.Eject, "EJECT REFERENCE");
        AmplifyButton.SetIcon(RMCIcons.SquarePlus, "AMPLIFY");
        SuppressButton.SetIcon(RMCIcons.SquareMinus, "SUPPRESS");
        AddButton.SetIcon(RMCIcons.ArrowRightLong, "ADD");
        RelateButton.SetIcon(RMCIcons.ArrowsRotate, "RELATE");
        FinalizeButton.SetIcon(RMCIcons.FloppyDisk, "FINALIZE");
    }

    public void SetCredits(int credits, int clearance)
    {
        CreditsLabel.Text = $"RESEARCH CREDITS: {credits}";
        ClearanceLabel.Text = $"CLEARANCE: {clearance}";

        var color = credits >= CreditsGoodThreshold ? GoodColor
            : credits >= CreditsDefaultThreshold ? ButtonColor
            : credits >= CreditsAverageThreshold ? AverageColor
            : BadColor;
        Bar(CreditsBar, (float) credits / CreditsBarMax, color);
    }

    public void SetNotice(PanelContainer panel, Label label, string text, Color color)
    {
        Notice(panel, label, text, color, _noticeFont);
    }

    public static void SetModeButton(RMCMachineButton button, bool selected)
    {
        button.Accent = selected ? ButtonSelectedColor : ButtonColor;
    }

    public sealed class PropertyButton : RMCMachineButton
    {
        public ProtoId<ChemGeneratorPropertyPrototype> PropertyId;
        public Action<ProtoId<ChemGeneratorPropertyPrototype>?>? OnSelect;

        public PropertyButton()
        {
            OnPressed += _ => OnSelect?.Invoke(Pressed ? PropertyId : (ProtoId<ChemGeneratorPropertyPrototype>?) null);
        }
    }

    public sealed class RecipeButton : RMCMachineButton
    {
        public int Index;
        public Action<int?>? OnSelect;

        public RecipeButton()
        {
            OnPressed += _ => OnSelect?.Invoke(Pressed ? Index : null);
        }
    }
}
