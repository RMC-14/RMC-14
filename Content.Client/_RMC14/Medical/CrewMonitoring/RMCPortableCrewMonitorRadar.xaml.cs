namespace Content.Client._RMC14.Medical.CrewMonitoring;

[GenerateTypedNameReferences]
public sealed partial class RMCPortableCrewMonitorRadar : LayoutContainer
{
    private const float DirectionArrowSize = 96;
    private const float CenterMessageTop = 8;
    private const float CenterMessageBottom = 40;

    private readonly IEyeManager _eye;

    private Vector2? _worldOffset;
    private float _range;
    private bool _directionOnly;
    private Angle? _lastEyeRotation;

    public Vector2? DisplayedOffset { get; private set; }

    public RMCPortableCrewMonitorRadar()
    {
        _eye = IoCManager.Resolve<IEyeManager>();
        RobustXamlLoader.Load(this);

        SetAnchorPreset(RadarGrid, LayoutPreset.Wide);
        SetAnchorPreset(DirectionArrow, LayoutPreset.Center);
        SetCenteredMargins(DirectionArrow, DirectionArrowSize);
        SetAnchorPreset(TargetName, LayoutPreset.TopWide);
        SetCenterMessageLayout(NoTarget);
        SetCenterMessageLayout(SignalLost);
    }

    public void SetTarget(bool selected, string targetName, Vector2? offset, float range, bool directionOnly)
    {
        TargetName.Text = selected ? targetName : string.Empty;
        TargetName.Visible = selected;
        NoTarget.Visible = !selected;
        SignalLost.Visible = selected && offset == null;

        _worldOffset = selected ? offset : null;
        _range = range;
        _directionOnly = selected && directionOnly;
        _lastEyeRotation = null;
        UpdateDisplay();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_lastEyeRotation != _eye.CurrentEye.Rotation)
            UpdateDisplay();
    }

    private void UpdateDisplay()
    {
        var eyeRotation = _eye.CurrentEye.Rotation;
        _lastEyeRotation = eyeRotation;

        Vector2? screenOffset = null;
        if (_worldOffset is { } worldOffset)
            screenOffset = eyeRotation.RotateVec(worldOffset);

        var showArrow = false;
        if (_directionOnly && screenOffset is { } direction)
        {
            showArrow = true;
            DirectionArrow.UpdateDirection(direction, Angle.Zero);
        }

        DirectionArrow.Visible = showArrow;
        DisplayedOffset = showArrow ? null : screenOffset;
        RadarGrid.SetTarget(DisplayedOffset, _range);
    }

    private static void SetCenteredMargins(Control control, float size)
    {
        var halfSize = size / 2;
        SetMarginLeft(control, -halfSize);
        SetMarginTop(control, -halfSize);
        SetMarginRight(control, halfSize);
        SetMarginBottom(control, halfSize);
    }

    private static void SetCenterMessageLayout(Control control)
    {
        SetAnchorPreset(control, LayoutPreset.HorizontalCenterWide);
        SetMarginLeft(control, 0);
        SetMarginTop(control, CenterMessageTop);
        SetMarginRight(control, 0);
        SetMarginBottom(control, CenterMessageBottom);
    }
}

public sealed class RMCPortableCrewMonitorRadarGrid : Control
{
    private const int Diameter = 48;

    private static readonly Color Background = Color.FromHex("#0D1718");
    private static readonly Color Border = Color.FromHex("#4A6769");
    private static readonly Color Grid = Color.FromHex("#264244").WithAlpha(0.55f);
    private static readonly Color MajorGrid = Color.FromHex("#426466").WithAlpha(0.7f);
    private static readonly Color Range = Color.FromHex("#5B8D79").WithAlpha(0.8f);
    private static readonly Color Center = Color.FromHex("#D8B56A");
    private static readonly Color Target = Color.FromHex("#56D364");

    private Vector2? _offset;
    private float _range = 24;

    public void SetTarget(Vector2? offset, float range)
    {
        _offset = offset;
        _range = MathF.Max(range, 1);
    }

    protected override void Draw(DrawingHandleScreen handle)
    {
        base.Draw(handle);

        var pixelSize = new Vector2(PixelSize.X, PixelSize.Y);
        var side = MathF.Min(pixelSize.X, pixelSize.Y) - 16 * UIScale;
        if (side <= 0)
            return;

        var topLeft = (pixelSize - new Vector2(side)) / 2;
        var bottomRight = topLeft + new Vector2(side);
        var box = new UIBox2(topLeft.X, topLeft.Y, bottomRight.X, bottomRight.Y);
        handle.DrawRect(box, Background);

        var tile = side / Diameter;
        for (var i = 0; i <= Diameter; i++)
        {
            var position = i * tile;
            var color = i % 4 == 0 ? MajorGrid : Grid;
            handle.DrawLine(topLeft + new Vector2(position, 0), topLeft + new Vector2(position, side), color);
            handle.DrawLine(topLeft + new Vector2(0, position), topLeft + new Vector2(side, position), color);
        }

        handle.DrawLine(topLeft, topLeft + new Vector2(side, 0), Border);
        handle.DrawLine(topLeft, topLeft + new Vector2(0, side), Border);
        handle.DrawLine(bottomRight, bottomRight - new Vector2(side, 0), Border);
        handle.DrawLine(bottomRight, bottomRight - new Vector2(0, side), Border);

        var center = topLeft + new Vector2(side / 2);
        handle.DrawCircle(center, side / 2 - UIScale, Range, false);
        handle.DrawCircle(center, 4 * UIScale, Center);

        if (_offset is not { } offset || offset.Length() > _range)
            return;

        var normalized = offset / (_range * 2) + new Vector2(0.5f, 0.5f);
        normalized.Y = 1 - normalized.Y;
        var target = topLeft + normalized * side;
        handle.DrawCircle(target, 7 * UIScale, Target.WithAlpha(0.25f));
        handle.DrawCircle(target, 4 * UIScale, Target);
    }
}
