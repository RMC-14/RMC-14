using System.Linq;
using System.Numerics;
using Content.Client._RMC14.TacticalMap.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._RMC14.TacticalMap.UI;

[GenerateTypedNameReferences]
public sealed partial class LabelTextDialog : DefaultWindow
{
    public event Action<string>? OnLabelConfirmed;
    public event Action? OnLabelDeleted;

    private bool _needsFocus;

    public LabelTextDialog()
    {
        RobustXamlLoader.Load(this);

        WindowHeader.Visible = false;
        WindowHeader.MinSize = Vector2.Zero;
        ContentsContainer.Margin = new Thickness(0);
        if (Children.FirstOrDefault(child => child.StyleClasses.Contains(StyleClassWindowPanel)) is { } panel)
            RemoveChild(panel);

        OkButton.OnPressed += _ => HandleConfirm();
        CancelButton.OnPressed += _ => Close();
        HeaderCloseButton.OnPressed += _ => Close();
        DeleteButton.OnPressed += _ => HandleDelete();
        TextEdit.OnTextEntered += _ => HandleConfirm();
    }

    private void Initialize(string existingText, TacticalMapTheme theme)
    {
        var edit = !string.IsNullOrEmpty(existingText);
        HeaderTitle.Text = Loc.GetString(edit
            ? "ui-tactical-map-label-dialog-edit-title"
            : "ui-tactical-map-label-dialog-create-title").ToUpperInvariant();

        TextEdit.Text = existingText;
        TextEdit.Editable = true;
        TextEdit.CanKeyboardFocus = true;
        TextEdit.StyleBoxOverride = TacticalMapStyle.Box(theme.Surface, theme.Border, padding: 4);
        DeleteButton.Visible = edit;
        TacticalMapStyle.ApplyTheme(this, theme);
        _needsFocus = true;
    }

    protected override void Opened()
    {
        base.Opened();
        _needsFocus = true;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (!_needsFocus)
            return;

        TextEdit.GrabKeyboardFocus();
        TextEdit.CursorPosition = TextEdit.Text.Length;
        _needsFocus = false;
    }

    private void HandleConfirm()
    {
        OnLabelConfirmed?.Invoke(TextEdit.Text.Trim());
        Close();
    }

    private void HandleDelete()
    {
        OnLabelDeleted?.Invoke();
        Close();
    }

    public static void Show(
        TacticalMapTheme theme,
        string existingText = "",
        Action<string>? onConfirmed = null,
        Action? onDeleted = null)
    {
        var dialog = new LabelTextDialog();
        dialog.Initialize(existingText, theme);
        if (onConfirmed != null)
            dialog.OnLabelConfirmed += onConfirmed;

        if (onDeleted != null)
            dialog.OnLabelDeleted += onDeleted;

        dialog.OpenCentered();
    }
}
