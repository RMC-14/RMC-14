using System.Numerics;
using Content.Client._RMC14.TacticalMap.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.TacticalMap.UI;

public enum TacticalMapToolKind
{
    None,
    Pen,
    Line,
    Rectangle,
    Eraser,
    Label,
}

[GenerateTypedNameReferences]
public sealed partial class TacticalMapToolPanel : BoxContainer, ITacticalMapThemed
{
    public static readonly (LocId Name, Color Color)[] Palette =
    {
        ("ui-tactical-map-color-black", Color.Black),
        ("ui-tactical-map-color-white", Color.White),
        ("ui-tactical-map-color-red", Color.FromHex("#F40002")),
        ("ui-tactical-map-color-orange", Color.FromHex("#F39504")),
        ("ui-tactical-map-color-blue", Color.FromHex("#015CF5")),
        ("ui-tactical-map-color-purple", Color.FromHex("#BF00F1")),
        ("ui-tactical-map-color-green", Color.FromHex("#00BB48")),
        ("ui-tactical-map-color-brown", Color.FromHex("#5A3121")),
    };

    private readonly List<TacticalMapButton> _colorButtons = new();
    private readonly List<EntityUid> _drawTargets = new();
    private TacticalMapTheme _theme = TacticalMapTheme.Marine;
    private TacticalMapToolKind _tool;
    private int _colorIndex;
    private bool _suppressDrawTarget;
    private bool _feedback;

    public event Action? SubmitPressed;
    public event Action? ClearPressed;
    public event Action? UndoPressed;
    public event Action<TacticalMapToolKind>? ToolChanged;
    public event Action<int>? ColorChanged;
    public event Action<float>? ThicknessChanged;
    public event Action<EntityUid>? DrawTargetSelected;

    public TacticalMapToolKind Tool => _tool;

    public TacticalMapToolPanel()
    {
        RobustXamlLoader.Load(this);

        UpdateButton.OnPressed += _ => SubmitPressed?.Invoke();
        ClearButton.OnPressed += _ => ClearPressed?.Invoke();
        UndoButton.OnPressed += _ => UndoPressed?.Invoke();
        PenButton.OnPressed += _ => ToggleTool(TacticalMapToolKind.Pen);
        LineButton.OnPressed += _ => ToggleTool(TacticalMapToolKind.Line);
        RectangleButton.OnPressed += _ => ToggleTool(TacticalMapToolKind.Rectangle);
        EraserButton.OnPressed += _ => ToggleTool(TacticalMapToolKind.Eraser);
        LabelButton.OnPressed += _ => ToggleTool(TacticalMapToolKind.Label);
        ThicknessSlider.OnValueChanged += args =>
        {
            UpdateThicknessLabel(args.Value);
            ThicknessChanged?.Invoke(args.Value);
        };

        DrawTargetButton.OnItemSelected += args =>
        {
            if (_suppressDrawTarget || args.Id < 0 || args.Id >= _drawTargets.Count)
                return;

            DrawTargetButton.SelectId(args.Id);
            DrawTargetSelected?.Invoke(_drawTargets[args.Id]);
        };

        for (var i = 0; i < Palette.Length; i++)
        {
            var index = i;
            var button = new TacticalMapButton
            {
                SetSize = new Vector2(26, 22),
                Swatch = Palette[i].Color,
                ToolTip = Loc.GetString(Palette[i].Name),
            };

            button.OnPressed += _ => SelectColor(index);
            _colorButtons.Add(button);
            ColorsContainer.AddChild(button);
        }

        UpdateThicknessLabel(ThicknessSlider.Value);
        UpdateToolButtons();
        ApplyTheme(_theme);
    }

    public void ApplyTheme(TacticalMapTheme theme)
    {
        _theme = theme;
        TacticalMapStyle.StyleSlider(ThicknessSlider, theme);
        TacticalMapStyle.StyleProgressBar(CooldownBar, theme, _feedback ? theme.Good : theme.Warning);
    }

    public void SetTool(TacticalMapToolKind tool)
    {
        _tool = tool;
        UpdateToolButtons();
    }

    public void SetColorIndex(int index)
    {
        _colorIndex = Math.Clamp(index, 0, Palette.Length - 1);
        UpdateColorButtons();
    }

    public void SetThickness(float thickness)
    {
        ThicknessSlider.SetValueWithoutEvent(thickness);
        UpdateThicknessLabel(thickness);
    }

    public void SetDrawTargets(IReadOnlyList<TacticalMapCanvasLayer> layers, EntityUid? drawTarget)
    {
        _suppressDrawTarget = true;
        var index = 0;
        var changed = false;
        foreach (var layer in layers)
        {
            if (!layer.Drawable)
                continue;

            if (index >= _drawTargets.Count || _drawTargets[index] != layer.Channel)
                changed = true;

            index++;
        }

        if (changed || index != _drawTargets.Count)
        {
            _drawTargets.Clear();
            DrawTargetButton.Clear();
            foreach (var layer in layers)
            {
                if (!layer.Drawable)
                    continue;

                DrawTargetButton.AddItem(layer.Name, _drawTargets.Count);
                _drawTargets.Add(layer.Channel);
            }
        }

        var selected = drawTarget == null ? -1 : _drawTargets.IndexOf(drawTarget.Value);
        if (selected >= 0 && DrawTargetButton.SelectedId != selected)
            DrawTargetButton.SelectId(selected);

        TargetSection.Visible = _drawTargets.Count > 1;
        _suppressDrawTarget = false;
    }

    public void SetCooldown(TimeSpan now, TimeSpan last, TimeSpan next, TimeSpan feedbackUntil, TimeSpan feedbackDuration)
    {
        if (now < feedbackUntil)
        {
            SetFeedback(true);
            CooldownBar.Visible = true;
            CooldownBar.MinValue = 0f;
            CooldownBar.MaxValue = (float) feedbackDuration.TotalSeconds;
            CooldownBar.Value = (float) (feedbackUntil - now).TotalSeconds;
            CooldownLabel.Text = Loc.GetString("ui-tactical-map-updated");
            UpdateButton.Disabled = false;
            return;
        }

        if (now >= next || next <= last)
        {
            CooldownBar.Visible = false;
            UpdateButton.Disabled = false;
            return;
        }

        SetFeedback(false);
        CooldownBar.Visible = true;
        CooldownBar.MinValue = 0f;
        CooldownBar.MaxValue = (float) (next - last).TotalSeconds;
        CooldownBar.Value = (float) (next - now).TotalSeconds;
        CooldownLabel.Text = Loc.GetString("ui-tactical-map-cooldown-seconds", ("seconds", (int) Math.Ceiling((next - now).TotalSeconds)));
        UpdateButton.Disabled = true;
    }

    private void SetFeedback(bool feedback)
    {
        if (_feedback == feedback)
            return;

        _feedback = feedback;
        TacticalMapStyle.StyleProgressBar(CooldownBar, _theme, feedback ? _theme.Good : _theme.Warning);
    }

    private void ToggleTool(TacticalMapToolKind tool)
    {
        _tool = _tool == tool ? TacticalMapToolKind.None : tool;
        UpdateToolButtons();
        ToolChanged?.Invoke(_tool);
    }

    private void SelectColor(int index)
    {
        _colorIndex = index;
        UpdateColorButtons();
        ColorChanged?.Invoke(index);
        if (_tool is TacticalMapToolKind.None or TacticalMapToolKind.Eraser)
            ToggleTool(TacticalMapToolKind.Pen);
    }

    private void UpdateToolButtons()
    {
        PenButton.Active = _tool == TacticalMapToolKind.Pen;
        LineButton.Active = _tool == TacticalMapToolKind.Line;
        RectangleButton.Active = _tool == TacticalMapToolKind.Rectangle;
        EraserButton.Active = _tool == TacticalMapToolKind.Eraser;
        LabelButton.Active = _tool == TacticalMapToolKind.Label;
        UpdateColorButtons();
    }

    private void UpdateColorButtons()
    {
        for (var i = 0; i < _colorButtons.Count; i++)
        {
            _colorButtons[i].Active = i == _colorIndex;
        }
    }

    private void UpdateThicknessLabel(float value)
    {
        WidthSection.Detail = Loc.GetString("ui-tactical-map-line-width-value", ("width", value.ToString("F1")));
    }
}
