using Content.Client._RMC14.TacticalMap.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._RMC14.TacticalMap.UI;

[GenerateTypedNameReferences]
public sealed partial class TacticalMapOverlayPanel : TacticalMapSection
{
    private static readonly ResPath AreaInfoRsi = new("/Textures/_RMC14/Structures/Machines/ceiling.rsi");

    private readonly TacticalMapButton[] _roofButtons = new TacticalMapButton[TacticalMapRoofLevels.Count];
    private TacticalMapOverlays _overlays;
    private TacticalMapRadiusMode _radius;

    public event Action<TacticalMapOverlays>? OverlaysChanged;
    public event Action<TacticalMapRadiusMode>? RadiusModeChanged;

    public TacticalMapOverlayPanel()
    {
        RobustXamlLoader.Load(this);

        var sprite = IoCManager.Resolve<IEntityManager>().System<SpriteSystem>();
        for (var level = 0; level < TacticalMapRoofLevels.Count; level++)
        {
            var flag = (TacticalMapOverlays) (1 << level);
            var button = new TacticalMapButton
            {
                Text = Loc.GetString($"ui-tactical-map-overlay-roof{level}"),
                Icon = sprite.Frame0(new SpriteSpecifier.Rsi(AreaInfoRsi, TacticalMapRoofLevels.GetState(level))),
                ToolTip = Loc.GetString($"ui-tactical-map-overlay-roof{level}-desc"),
                AlignLeft = true,
                HorizontalExpand = true,
                MinHeight = 22,
            };

            button.OnPressed += _ => Toggle(flag);
            _roofButtons[level] = button;
            RoofList.AddChild(button);
        }

        LinkedLzButton.OnPressed += _ => Toggle(TacticalMapOverlays.LinkedLz);
        OrbitalButton.OnPressed += _ => ToggleRadius(TacticalMapRadiusMode.OrbitalBombardment);
        MortarButton.OnPressed += _ => ToggleRadius(TacticalMapRadiusMode.Mortar);
        UpdateButtons();
    }

    public void SetState(TacticalMapOverlays overlays, TacticalMapRadiusMode radius)
    {
        _overlays = overlays;
        _radius = radius;
        UpdateButtons();
    }

    private void Toggle(TacticalMapOverlays flag)
    {
        _overlays ^= flag;
        UpdateButtons();
        OverlaysChanged?.Invoke(_overlays);
    }

    private void ToggleRadius(TacticalMapRadiusMode mode)
    {
        _radius = _radius == mode ? TacticalMapRadiusMode.None : mode;
        UpdateButtons();
        RadiusModeChanged?.Invoke(_radius);
    }

    private void UpdateButtons()
    {
        var active = 0;
        for (var level = 0; level < _roofButtons.Length; level++)
        {
            var on = (_overlays & (TacticalMapOverlays) (1 << level)) != 0;
            _roofButtons[level].Active = on;
            if (on)
                active++;
        }

        var lz = (_overlays & TacticalMapOverlays.LinkedLz) != 0;
        LinkedLzButton.Active = lz;
        if (lz)
            active++;

        OrbitalButton.Active = _radius == TacticalMapRadiusMode.OrbitalBombardment;
        MortarButton.Active = _radius == TacticalMapRadiusMode.Mortar;
        Detail = active > 0 ? Loc.GetString("ui-tactical-map-overlay-active-count", ("count", active)) : null;
    }
}
