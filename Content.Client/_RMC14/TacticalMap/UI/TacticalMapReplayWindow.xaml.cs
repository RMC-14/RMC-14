using System.Linq;
using System.Numerics;
using Content.Client._RMC14.TacticalMap.Controls;
using Content.Shared._RMC14.TacticalMap;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._RMC14.TacticalMap.UI;

[GenerateTypedNameReferences]
public sealed partial class TacticalMapReplayWindow : DefaultWindow
{
    [Dependency] private readonly IEntityManager _entMan = default!;

    private static readonly float[] Speeds = { 10f, 30f, 60f, 120f, 300f };
    private const int DefaultSpeedIndex = 2;

    private readonly List<TacticalMapReplayMap> _maps = new();
    private readonly List<List<TacticalMapReplayFrame>> _frames = new();
    private readonly HashSet<int> _hiddenChannels = new();
    private readonly HashSet<int> _seenEntities = new();
    private readonly Dictionary<int, TacticalMapReplayCanvas> _latestCanvases = new();
    private readonly List<TacticalMapBlipView> _blips = new();
    private readonly List<TacticalMapCanvasLayer> _layers = new();
    private int _mapIndex = -1;
    private int _speedIndex = DefaultSpeedIndex;
    private bool _playing;
    private float _start;
    private float _end;
    private float _time;
    private int _shownFrame = -2;
    private int _shownCanvases = -1;
    private bool _dirty;

    public TacticalMapReplayWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        WindowHeader.Visible = false;
        WindowHeader.MinSize = Vector2.Zero;
        ContentsContainer.Margin = new Thickness(0);
        if (Children.FirstOrDefault(child => child.StyleClasses.Contains(StyleClassWindowPanel)) is { } panel)
            RemoveChild(panel);

        HeaderTitle.Text = "TACTICAL MAP REPLAY";
        HeaderCloseButton.OnPressed += _ => Close();
        TacticalMapStyle.ApplyTheme(this, TacticalMapTheme.Marine);
        TacticalMapStyle.StyleSlider(Timeline, TacticalMapTheme.Marine);

        Map.AllowBlipClicks = false;

        MapSelect.OnItemSelected += args =>
        {
            MapSelect.SelectId(args.Id);
            SelectMap(args.Id);
        };

        PlayButton.OnPressed += _ =>
        {
            if (!_playing && _time >= _end)
                _time = _start;

            _playing = !_playing;
            _dirty = true;
            UpdateControls();
        };

        SpeedButton.OnPressed += _ =>
        {
            _speedIndex = (_speedIndex + 1) % Speeds.Length;
            UpdateControls();
        };

        Timeline.OnValueChanged += range =>
        {
            _time = _start + range.Value;
            _dirty = true;
        };

        UpdateControls();
    }

    public void SetReplay(List<TacticalMapReplayMap> maps)
    {
        _maps.Clear();
        _maps.AddRange(maps);
        _frames.Clear();
        foreach (var map in _maps)
        {
            _frames.Add(new List<TacticalMapReplayFrame>(map.FrameCount));
        }

        MapSelect.Clear();
        for (var i = 0; i < _maps.Count; i++)
        {
            MapSelect.AddItem(_maps[i].Name, i);
        }

        MapSelect.Visible = _maps.Count > 1;
        EmptyLabel.Visible = _maps.Count == 0;
        SelectMap(_maps.Count > 0 ? 0 : -1);
    }

    public void AddFrames(int mapIndex, List<TacticalMapReplayFrame> frames)
    {
        if (mapIndex < 0 || mapIndex >= _frames.Count)
            return;

        _frames[mapIndex].AddRange(frames);
        if (mapIndex != _mapIndex)
            return;

        UpdateRange();
        _dirty = true;
    }

    private void SelectMap(int index)
    {
        _mapIndex = index;
        _playing = false;
        _time = 0;
        _hiddenChannels.Clear();
        ChannelList.RemoveAllChildren();

        if (index < 0 || index >= _maps.Count)
        {
            Map.SetBaseMap(null);
            Map.SetBlips(Array.Empty<TacticalMapBlipView>());
            Map.SetLayers(Array.Empty<TacticalMapCanvasLayer>());
            UpdateControls();
            return;
        }

        var map = _maps[index];
        Map.SetBaseMap(_entMan.TryGetEntity(map.Map, out var mapUid) ? mapUid : null);

        for (var i = 0; i < map.Channels.Count; i++)
        {
            var channelIndex = i;
            var channel = map.Channels[i];
            var button = new TacticalMapButton
            {
                Text = channel.Name,
                Active = true,
                AlignLeft = true,
                HorizontalExpand = true,
                MinHeight = 22,
            };

            button.OnPressed += _ =>
            {
                if (!_hiddenChannels.Remove(channelIndex))
                    _hiddenChannels.Add(channelIndex);

                button.Active = !_hiddenChannels.Contains(channelIndex);
                _dirty = true;
            };

            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 3,
                HorizontalExpand = true,
            };

            row.AddChild(new PanelContainer
            {
                SetSize = new Vector2(6, 22),
                PanelOverride = TacticalMapStyle.Box(channel.Color, TacticalMapTheme.Marine.Border),
            });

            row.AddChild(button);
            ChannelList.AddChild(row);
        }

        TacticalMapStyle.ApplyTheme(ChannelList, TacticalMapTheme.Marine);

        UpdateRange();
        _dirty = true;
        UpdateControls();
    }

    private void UpdateRange()
    {
        if (_mapIndex < 0)
            return;

        var start = float.MaxValue;
        var end = float.MinValue;
        var frames = _frames[_mapIndex];
        if (frames.Count > 0)
        {
            start = frames[0].Time;
            end = frames[^1].Time;
        }

        foreach (var canvas in _maps[_mapIndex].Canvases)
        {
            start = MathF.Min(start, canvas.Time);
            end = MathF.Max(end, canvas.Time);
        }

        if (start > end)
        {
            start = 0;
            end = 0;
        }

        _start = start;
        _end = end;
        _time = Math.Clamp(_time, _start, _end);
        Timeline.MaxValue = MathF.Max(_end - _start, 0.001f);
        Timeline.SetValueWithoutEvent(_time - _start);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_mapIndex < 0)
            return;

        if (_playing && !Timeline.Grabbed)
        {
            _time += args.DeltaSeconds * Speeds[_speedIndex];
            if (_time >= _end)
            {
                _time = _end;
                _playing = false;
                UpdateControls();
            }

            Timeline.SetValueWithoutEvent(_time - _start);
        }

        var frame = FindFrame(_time);
        var canvases = CountCanvases(_time);
        if (_dirty || frame != _shownFrame || canvases != _shownCanvases)
        {
            _dirty = false;
            _shownFrame = frame;
            _shownCanvases = canvases;
            Render(frame, canvases);
        }

        TimeLabel.Text = $"{FormatTime(_time - _start)} / {FormatTime(_end - _start)}";
    }

    private int FindFrame(float time)
    {
        var frames = _frames[_mapIndex];
        var low = 0;
        var high = frames.Count - 1;
        var result = -1;
        while (low <= high)
        {
            var mid = (low + high) / 2;
            if (frames[mid].Time <= time)
            {
                result = mid;
                low = mid + 1;
            }
            else
            {
                high = mid - 1;
            }
        }

        return result;
    }

    private int CountCanvases(float time)
    {
        var canvases = _maps[_mapIndex].Canvases;
        var low = 0;
        var high = canvases.Count - 1;
        var count = 0;
        while (low <= high)
        {
            var mid = (low + high) / 2;
            if (canvases[mid].Time <= time)
            {
                count = mid + 1;
                low = mid + 1;
            }
            else
            {
                high = mid - 1;
            }
        }

        return count;
    }

    private void Render(int frameIndex, int canvasCount)
    {
        var map = _maps[_mapIndex];
        _blips.Clear();
        _seenEntities.Clear();
        if (frameIndex >= 0)
        {
            foreach (var blip in _frames[_mapIndex][frameIndex].Blips)
            {
                if (_hiddenChannels.Contains(blip.Channel) ||
                    blip.Icon >= map.Icons.Count ||
                    !_seenEntities.Add(blip.Entity))
                {
                    continue;
                }

                SpriteSpecifier.Rsi? background = null;
                if (blip.Background != TacticalMapReplayBlip.NoBackground && blip.Background < map.Icons.Count)
                    background = map.Icons[blip.Background];

                _blips.Add(new TacticalMapBlipView(
                    new NetEntity(blip.Entity),
                    new TacticalMapBlip(
                        new Vector2i(blip.X, blip.Y),
                        map.Icons[blip.Icon],
                        background,
                        SharedTacticalMapSystem.UnpackColor(blip.Color),
                        (TacticalMapBlipFlags) blip.Flags,
                        TimeSpan.Zero,
                        TimeSpan.Zero)));
            }
        }

        Map.SetBlips(_blips);

        _latestCanvases.Clear();
        for (var i = 0; i < canvasCount; i++)
        {
            var canvas = map.Canvases[i];
            _latestCanvases[canvas.Channel] = canvas;
        }

        _layers.Clear();
        foreach (var (channelIndex, canvas) in _latestCanvases)
        {
            if (_hiddenChannels.Contains(channelIndex))
                continue;

            var channel = channelIndex < map.Channels.Count ? map.Channels[channelIndex] : default;
            _layers.Add(new TacticalMapCanvasLayer
            {
                Name = channel.Name ?? string.Empty,
                Color = channel.Color,
                SortOrder = channelIndex,
                Strokes = canvas.Strokes,
                Labels = canvas.Labels,
            });
        }

        _layers.Sort(static (a, b) => a.SortOrder.CompareTo(b.SortOrder));
        Map.SetLayers(_layers);
    }

    private void UpdateControls()
    {
        PlayButton.Text = _playing ? "Pause" : "Play";
        SpeedButton.Text = $"x{Speeds[_speedIndex]}";
        PlayButton.Disabled = _mapIndex < 0;
        SpeedButton.Disabled = _mapIndex < 0;
        Timeline.Disabled = _mapIndex < 0;
    }

    private static string FormatTime(float seconds)
    {
        return TimeSpan.FromSeconds(MathF.Max(0, seconds)).ToString(@"hh\:mm\:ss");
    }
}
