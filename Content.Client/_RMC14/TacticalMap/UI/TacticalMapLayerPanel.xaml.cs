using System.Numerics;
using Content.Client._RMC14.TacticalMap.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.TacticalMap.UI;

[GenerateTypedNameReferences]
public sealed partial class TacticalMapLayerPanel : TacticalMapSection
{
    private readonly List<EntityUid> _channels = new();
    private readonly Dictionary<EntityUid, TacticalMapButton> _buttons = new();
    private readonly Dictionary<EntityUid, PanelContainer> _chips = new();
    private readonly Dictionary<EntityUid, Color> _colors = new();
    private TacticalMapTheme _theme = TacticalMapTheme.Marine;

    public event Action<EntityUid>? VisibilityToggled;

    public TacticalMapLayerPanel()
    {
        RobustXamlLoader.Load(this);
    }

    public override void ApplyTheme(TacticalMapTheme theme)
    {
        base.ApplyTheme(theme);
        _theme = theme;
        foreach (var (channel, chip) in _chips)
        {
            chip.PanelOverride = TacticalMapStyle.Box(_colors.GetValueOrDefault(channel, theme.Text), theme.Border);
        }
    }

    public void SetLayers(IReadOnlyList<TacticalMapCanvasLayer> layers, IReadOnlySet<EntityUid> hidden)
    {
        var changed = layers.Count != _channels.Count;
        for (var i = 0; !changed && i < layers.Count; i++)
        {
            changed = layers[i].Channel != _channels[i];
        }

        if (changed)
        {
            _channels.Clear();
            _buttons.Clear();
            _chips.Clear();
            _colors.Clear();
            LayerList.RemoveAllChildren();
            foreach (var layer in layers)
            {
                var channel = layer.Channel;
                var chip = new PanelContainer
                {
                    SetSize = new Vector2(6, 22),
                    PanelOverride = TacticalMapStyle.Box(layer.Color, _theme.Border),
                };

                var button = new TacticalMapButton
                {
                    MinHeight = 22,
                    HorizontalExpand = true,
                    AlignLeft = true,
                };

                button.ApplyTheme(_theme);
                button.OnPressed += _ => VisibilityToggled?.Invoke(channel);

                var row = new BoxContainer
                {
                    Orientation = LayoutOrientation.Horizontal,
                    SeparationOverride = 3,
                    HorizontalExpand = true,
                };

                row.AddChild(chip);
                row.AddChild(button);
                LayerList.AddChild(row);

                _channels.Add(channel);
                _buttons[channel] = button;
                _chips[channel] = chip;
                _colors[channel] = layer.Color;
            }
        }

        var visibleCount = 0;
        foreach (var layer in layers)
        {
            var visible = !hidden.Contains(layer.Channel);
            if (visible)
                visibleCount++;

            if (!_buttons.TryGetValue(layer.Channel, out var button))
                continue;

            button.Active = visible;
            button.Text = layer.Name;
            button.ToolTip = Loc.GetString(visible ? "ui-tactical-map-layer-hide-tooltip" : "ui-tactical-map-layer-show-tooltip");
        }

        Detail = Loc.GetString("ui-tactical-map-layer-visibility-summary",
            ("selected", visibleCount),
            ("total", layers.Count));
    }
}
