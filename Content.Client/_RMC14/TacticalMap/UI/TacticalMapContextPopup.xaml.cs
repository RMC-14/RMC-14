using Content.Client._RMC14.TacticalMap.Controls;
using Content.Shared._RMC14.TacticalMap;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._RMC14.TacticalMap.UI;

[GenerateTypedNameReferences]
public sealed partial class TacticalMapContextPopup : Popup, ITacticalMapThemed
{
    private static readonly ResPath AreaInfoRsiPath = new("/Textures/_RMC14/Structures/Machines/ceiling.rsi");

    private static readonly (TacticalMapTileFlags Flag, LocId Name)[] Actions =
    {
        (TacticalMapTileFlags.OrbitalBombard, "ui-tactical-map-action-ob"),
        (TacticalMapTileFlags.CAS, "ui-tactical-map-action-cas"),
        (TacticalMapTileFlags.SupplyDrop, "ui-tactical-map-action-supply"),
        (TacticalMapTileFlags.MortarFire, "ui-tactical-map-action-mortar-fire"),
        (TacticalMapTileFlags.MortarPlacement, "ui-tactical-map-action-mortar-place"),
        (TacticalMapTileFlags.Lase, "ui-tactical-map-action-lase"),
        (TacticalMapTileFlags.Medevac, "ui-tactical-map-action-medevac"),
        (TacticalMapTileFlags.Paradrop, "ui-tactical-map-action-paradrop"),
        (TacticalMapTileFlags.Fulton, "ui-tactical-map-action-fulton"),
        (TacticalMapTileFlags.LandingZone, "ui-tactical-map-action-landing-zone"),
    };

    private readonly SpriteSystem _sprite;
    private TacticalMapTheme _theme = TacticalMapTheme.Marine;

    public Action? OnCreateLabelPressed;
    public Action? OnCreateMortarPressed;
    public Action? OnDeleteMortarPressed;
    public Action? OnCopyCoordinatesPressed;

    public TacticalMapContextPopup()
    {
        RobustXamlLoader.Load(this);
        _sprite = IoCManager.Resolve<IEntityManager>().System<SpriteSystem>();

        CreateLabelButton.OnPressed += _ => OnCreateLabelPressed?.Invoke();
        CreateMortarButton.OnPressed += _ => OnCreateMortarPressed?.Invoke();
        DeleteMortarButton.OnPressed += _ => OnDeleteMortarPressed?.Invoke();
        CopyCoordinatesButton.OnPressed += _ => OnCopyCoordinatesPressed?.Invoke();

        UserInterfaceManager.ModalRoot.AddChild(this);
    }

    public void ApplyTheme(TacticalMapTheme theme)
    {
        _theme = theme;
    }

    public void SetInfo(
        TacticalMapAreaInfo info,
        bool showCoordinates,
        bool showCreateLabel,
        bool showDeleteMortar,
        bool showCopyCoordinates)
    {
        AreaNameLabel.Text = info.AreaName;
        var state = TacticalMapRoofLevels.GetState(TacticalMapRoofLevels.GetLevel(info.Effective));
        AreaIcon.Texture = _sprite.Frame0(new SpriteSpecifier.Rsi(AreaInfoRsiPath, state));

        InfoContainer.RemoveAllChildren();
        if (showCoordinates)
            AddInfoLine(Loc.GetString("ui-tactical-map-context-coords", ("x", info.Indices.X), ("y", info.Indices.Y)));

        if (!string.IsNullOrWhiteSpace(info.LinkedLz))
            AddInfoLine(Loc.GetString("ui-tactical-map-context-linked-lz", ("lz", info.LinkedLz)));

        if (!string.IsNullOrWhiteSpace(info.TacticalLabel))
            AddInfoLine(Loc.GetString("ui-tactical-map-context-tactical-label", ("label", info.TacticalLabel)), _theme.Text);

        if (!string.IsNullOrWhiteSpace(info.AreaLabel))
            AddInfoLine(Loc.GetString("ui-tactical-map-context-area-label", ("label", info.AreaLabel)));

        InfoContainer.Visible = InfoContainer.ChildCount > 0;

        ActionRow.RemoveAllChildren();
        if (info.HasArea)
        {
            var allowed = new List<string>();
            var blocked = new List<string>();
            foreach (var (flag, name) in Actions)
            {
                (info.Allows(flag) ? allowed : blocked).Add(Loc.GetString(name));
            }

            if (allowed.Count > 0)
                ActionRow.AddChild(BuildActionColumn("ui-tactical-map-context-allowed-title", allowed, "+", _theme.Good));

            if (blocked.Count > 0)
                ActionRow.AddChild(BuildActionColumn("ui-tactical-map-context-blocked-title", blocked, "-", _theme.Danger));
        }

        ActionRow.Visible = ActionRow.ChildCount > 0;

        CreateLabelButton.Text = Loc.GetString(string.IsNullOrWhiteSpace(info.TacticalLabel)
            ? "ui-tactical-map-label-dialog-create-title"
            : "ui-tactical-map-label-dialog-edit-title");
        CreateLabelButton.Visible = showCreateLabel;
        CreateMortarButton.Text = Loc.GetString("ui-tactical-map-create-mortar");
        CreateMortarButton.Disabled = info.HasArea && !info.Allows(TacticalMapTileFlags.MortarPlacement);
        DeleteMortarButton.Text = Loc.GetString("ui-tactical-map-remove-mortar");
        DeleteMortarButton.Visible = showDeleteMortar;
        CopyCoordinatesButton.Text = Loc.GetString("ui-tactical-map-copy-coordinates");
        CopyCoordinatesButton.Visible = showCopyCoordinates;

        TacticalMapStyle.ApplyTheme(this, _theme);
    }

    private void AddInfoLine(string text, Color? color = null)
    {
        InfoContainer.AddChild(new TacticalMapLabel
        {
            Text = text,
            TextStyle = TacticalMapTextStyle.Small,
            ColorOverride = color ?? _theme.TextMuted,
        });
    }

    private BoxContainer BuildActionColumn(string titleKey, List<string> actions, string prefix, Color color)
    {
        var column = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SeparationOverride = 1,
        };

        column.AddChild(new TacticalMapLabel
        {
            Text = Loc.GetString(titleKey).ToUpperInvariant(),
            TextStyle = TacticalMapTextStyle.Heading,
            ColorOverride = color,
        });

        foreach (var action in actions)
        {
            column.AddChild(new TacticalMapLabel
            {
                Text = $"{prefix} {action}",
                TextStyle = TacticalMapTextStyle.Small,
                ColorOverride = color.WithAlpha(0.85f),
            });
        }

        return column;
    }
}
