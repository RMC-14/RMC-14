using System.Linq;
using System.Numerics;
using Content.Client._RMC14.UserInterface;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.TacticalMap.UI;

[GenerateTypedNameReferences]
public sealed partial class TacticalMapWindow : RMCPopOutWindow
{
    [Dependency] private readonly TacticalMapSettingsManager _settings = default!;

    private bool _poppedOut;

    protected override Control Control => View;

    public TacticalMapWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        if (_settings.WindowSize is { } size)
            SetSize = size;

        WindowHeader.Visible = false;
        WindowHeader.MinSize = Vector2.Zero;
        ContentsContainer.Margin = new Thickness(0);

        if (Children.FirstOrDefault(child => child.StyleClasses.Contains(StyleClassWindowPanel)) is { } panel)
            RemoveChild(panel);

        View.PopoutRequested += PopOut;
        View.CloseRequested += OnCloseRequested;
        OnPopout += () =>
        {
            _poppedOut = true;
            View.SetPopoutVisible(false);
        };
    }

    private void OnCloseRequested()
    {
        if (_poppedOut)
            DisposePopOut();
        else
            Close();
    }

    public void RestorePosition()
    {
        if (_settings.WindowPosition is not { } position || Parent is not { } parent)
            return;

        var size = new Vector2(
            float.IsNaN(SetWidth) ? Width : SetWidth,
            float.IsNaN(SetHeight) ? Height : SetHeight);
        var max = Vector2.Max(parent.Size - size, Vector2.Zero);
        LayoutContainer.SetPosition(this, Vector2.Clamp(position, Vector2.Zero, max));
    }

    public void SaveBounds()
    {
        if (_poppedOut || Width <= 0 || Height <= 0)
            return;

        _settings.WindowSize = Size;
        _settings.WindowPosition = Position;
    }
}
