    {
        Map.DrawThickness = thickness;
        _settings.LineThickness = thickness;
    }

    private void OnPointClicked(Vector2i indices)
    {
        if (_selectedMap is { } map)
            PointActivated?.Invoke(map, indices);
    }

    private void OnContextMenuRequested(Vector2i indices, Vector2 screen)
    {
        _contextPopup ??= new TacticalMapContextPopup();
        var info = Map.GetAreaInfo(indices);
        var adminGhost = IsAdminGhost();
        var canLabel = _drawing && Map.Draft != null;
        var popup = _contextPopup;

        popup.OnCreateLabelPressed = () =>
        {
            Map.OpenLabelDialog(indices);
            popup.Close();
        };

        popup.OnCreateMortarPressed = () =>
        {
            Map.SetMortarMarker(indices, _mortarRange.Min, _mortarRange.Max);
            popup.Close();
        };

        popup.OnDeleteMortarPressed = () =>
        {
            Map.ClearMortarMarker();
            popup.Close();
        };

        popup.OnCopyCoordinatesPressed = () =>
        {
            _clipboard.SetText(Loc.GetString("ui-tactical-map-copy-coords-format", ("x", indices.X), ("y", indices.Y)));
            popup.Close();
        };

        popup.ApplyTheme(_theme);
        popup.SetInfo(info, adminGhost, canLabel, Map.IsMortarMarkerTile(indices), adminGhost);
        popup.Open(UIBox2.FromDimensions(screen, new Vector2(1, 1)));
        popup.SetPositionLast();
    }

    private bool IsAdminGhost()
    {
        return _player.LocalEntity is { } player &&
               _entMan.TryGetComponent(player, out GhostComponent? ghost) &&
               ghost.CanGhostInteract;
    }

    private void OnHoverChanged(Vector2i? indices)
    {
        if (indices is not { } tile)
        {
            HoverAreaLabel.Text = string.Empty;
            HoverAreaIcon.Visible = false;
            return;
        }

        var info = Map.GetAreaInfo(tile);
        HoverAreaLabel.Text = info.AreaName;
        var state = TacticalMapRoofLevels.GetState(TacticalMapRoofLevels.GetLevel(info.Effective));
        HoverAreaIcon.Texture = _sprite.Frame0(new SpriteSpecifier.Rsi(AreaInfoRsi, state));
        HoverAreaIcon.Visible = true;
    }

    // panning or zooming by hand stops follow
    private void OnUserInteraction()
    {
        if (!_following)
            return;

        _following = false;
        UpdateButtons();
    }

