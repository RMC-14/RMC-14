    private void LoadSettings()
    {
        Map.BlipSizeMultiplier = _settings.BlipSize;
        BlipSizeSlider.SetValueWithoutEvent(Map.BlipSizeMultiplier);
        UpdateBlipSizeLabel();

        Map.DrawThickness = _settings.LineThickness;
        ToolPanel.SetThickness(Map.DrawThickness);

        var colorIndex = Math.Clamp(_settings.ColorIndex, 0, TacticalMapToolPanel.Palette.Length - 1);
        Map.DrawColor = TacticalMapToolPanel.Palette[colorIndex].Color;
        ToolPanel.SetColorIndex(colorIndex);

        Map.LabelMode = _settings.LabelMode;
        Map.LabelsEnabled = _settings.LabelsEnabled;
        Map.CrtOverlay = _settings.CrtEffect;
        _objectivesVisible = _settings.ObjectivesVisible;
        _overlaysVisible = _settings.OverlaysVisible;
        _displayVisible = _settings.DisplayVisible;
    }

    private void LoadPreviewRanges()
    {
        Map.HiveCoreRange = TacticalMapRadiusPreview.GetHiveCoreRange(_prototypes, _componentFactory, Map.HiveCoreRange);
        Map.HivePylonRange = TacticalMapRadiusPreview.GetHivePylonRange(_prototypes, _componentFactory, Map.HivePylonRange);
        _mortarRange = TacticalMapRadiusPreview.GetMortarRange(_prototypes, _componentFactory, _mortarRange);
    }

    // keyed by map name so the saved view survives across rounds
    private string? GetViewKey()
    {
        if (_selectedMap is not { } map)
            return null;

        foreach (var option in _maps)
        {
            if (option.Map == map)
                return option.Name;
        }

        return null;
    }

    public void SaveViewState()
    {
        if (GetViewKey() is { } key)
            _settings.SetViewState(key, Map.Zoom, Map.Pan);
    }

    private void LoadViewState()
    {
        if (GetViewKey() is { } key && _settings.TryGetViewState(key, out var zoom, out var pan))
            Map.SetView(zoom, pan);
        else
            Map.SetView(1f, Vector2.Zero);
    }

    private void UpdatePanels()
    {
        var showUi = !_focus || _focusHovered;
        WindowFrame.Kind = showUi ? TacticalMapPanelKind.Frame : TacticalMapPanelKind.None;
        TitleBar.Visible = showUi;
        Toolbar.Visible = showUi;
        StatusBar.Visible = showUi;
        ToolPanel.Visible = showUi && _drawing;
        SidePanelContainer.Visible = showUi && SidePanelContainer.ChildCount > 0;

        var hasLayers = _layers.Count > 1;
        LayerPanel.Visible = hasLayers && _layersVisible;
        OverlayPanel.Visible = _overlaysVisible;
        ObjectivesSection.Visible = _hasObjectives && _objectivesVisible;
        DisplaySection.Visible = _displayVisible;
        Sidebar.Visible = showUi &&
                          (LayerPanel.Visible || OverlayPanel.Visible || ObjectivesSection.Visible || DisplaySection.Visible);

        LayersButton.Visible = hasLayers;
        ObjectivesButton.Visible = _hasObjectives;
        MapContainer.Margin = showUi ? new Thickness(4) : new Thickness(0);
        OverlayPanel.SetState(Map.Overlays);
    }

    private void UpdateButtons()
    {
        LabelsButton.Active = Map.LabelsEnabled;
        LabelModeAllButton.Active = Map.LabelMode == TacticalMapLabelMode.All;
        LabelModeTacticalButton.Active = Map.LabelMode == TacticalMapLabelMode.Tactical;
        LabelModeAreaButton.Active = Map.LabelMode == TacticalMapLabelMode.Area;
        FollowButton.Active = _following;
        LayersButton.Active = _layersVisible;
        OverlaysButton.Active = _overlaysVisible;
        ObjectivesButton.Active = _objectivesVisible;
        SettingsButton.Active = _displayVisible;
        FocusButton.Active = _focus;
        CrtButton.Active = Map.CrtOverlay;
    }

    private void UpdateBlipSizeLabel()
    {
        BlipSizeLabel.Text = Loc.GetString("ui-tactical-map-blip-size-label", ("size", Map.BlipSizeMultiplier.ToString("F1"))).ToUpperInvariant();
    }

    private void UpdateFeedLabel()
    {
        if (_live)
        {
            FeedLabel.Text = Loc.GetString("ui-tactical-map-feed-live");
            FeedLabel.ColorOverride = _theme.Good;
            return;
        }

        if (_snapshotAt is not { } snapshotAt)
        {
            FeedLabel.Text = Loc.GetString("ui-tactical-map-feed-none");
            FeedLabel.ColorOverride = _theme.TextMuted;
            return;
        }

        var age = _timing.CurTime - snapshotAt;
        FeedLabel.Text = Loc.GetString("ui-tactical-map-feed-updated", ("minutes", Math.Max(0, (int) age.TotalMinutes)));
        FeedLabel.ColorOverride = age.TotalSeconds > StaleFadeStart ? _theme.Warning : _theme.TextMuted;
    }

    private void UpdateModeLabel()
    {
        if (Map.Tool != null && _drawLayer is { } layer)
        {
            ModeLabel.Text = Loc.GetString("ui-tactical-map-mode-drawing", ("layer", layer.Name));
            ModeLabel.ColorOverride = _theme.Text;
        }
        else if (Map.PointMode)
        {
            ModeLabel.Text = Loc.GetString("ui-tactical-map-mode-point");
            ModeLabel.ColorOverride = _theme.Warning;
        }
        else
        {
            ModeLabel.Text = Loc.GetString("ui-tactical-map-mode-hint");
            ModeLabel.ColorOverride = _theme.TextMuted;
        }
    }

    private void RegisterCompactButtons()
    {
        foreach (var button in new[]
                 {
                     LabelsButton, FollowButton, ResetViewButton, LayersButton, OverlaysButton,
                     ObjectivesButton, SettingsButton,
                 })
        {
            _compactButtons[button] = (button.Text ?? string.Empty, button.MinWidth);
        }
    }

    private void ApplyCompact()
    {
        var compact = MainButtonRow.Width > 0f && MainButtonRow.Width <= CompactThreshold;
        foreach (var (button, entry) in _compactButtons)
        {
            if (compact && entry.Text.Length > 1)
            {
                button.Text = entry.Text.Substring(0, 1);
                button.MinWidth = CompactButtonWidth;
            }
            else
            {
                button.Text = entry.Text;
                button.MinWidth = entry.MinWidth;
            }

            button.ToolTip = entry.Text;
        }
    }

    protected override void Resized()
    {
        base.Resized();
        ApplyCompact();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        Frame?.Invoke();
        UpdateStaleAlpha();
        UpdateFollow(args.DeltaSeconds);
        UpdateFocusHover();
        UpdateCooldown();

        _feedTimer += args.DeltaSeconds;
        if (_feedTimer < FeedInterval)
            return;

        _feedTimer = 0f;
        UpdateFeedLabel();
    }

    // snapshot blips fade out as they get older
    private void UpdateStaleAlpha()
    {
        if (_live || _snapshotAt is not { } since)
        {
            Map.BlipAlpha = 1f;
            return;
        }

        var age = (float) (_timing.CurTime - since).TotalSeconds;
        if (age <= StaleFadeStart)
            Map.BlipAlpha = 1f;
        else if (age >= StaleFadeEnd)
            Map.BlipAlpha = StaleMinAlpha;
        else
            Map.BlipAlpha = 1f - (1f - StaleMinAlpha) * (age - StaleFadeStart) / (StaleFadeEnd - StaleFadeStart);
    }

    private void UpdateFollow(float delta)
    {
        if (!_following)
            return;

        _followTimer += delta;
        if (_followTimer < FollowInterval)
            return;

        _followTimer = 0f;
        if (Map.SelfIndices is { } self && self != _lastFollow && Map.CenterOn(self))
            _lastFollow = self;
    }

    private void UpdateFocusHover()
    {
        if (!_focus)
            return;

        // focus mode hides the ui until the mouse comes near the window
        var mouse = _ui.MousePositionScaled.Position;
        var rect = GlobalRect;
        var dx = mouse.X < rect.Left ? rect.Left - mouse.X : mouse.X > rect.Right ? mouse.X - rect.Right : 0f;
        var dy = mouse.Y < rect.Top ? rect.Top - mouse.Y : mouse.Y > rect.Bottom ? mouse.Y - rect.Bottom : 0f;
        var hovered = MathF.Sqrt(dx * dx + dy * dy) <= FocusHoverGrace;
        if (hovered == _focusHovered)
            return;

        _focusHovered = hovered;
        UpdatePanels();
    }

    private void UpdateCooldown()
    {
        if (!_drawing || _drawLayer is not { } layer)
            return;

        ToolPanel.SetCooldown(_timing.CurTime, layer.LastSubmitAt, layer.NextSubmitAt, _feedbackUntil, FeedbackDuration);
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        SaveViewState();
        _contextPopup?.Orphan();
        _contextPopup = null;
    }
