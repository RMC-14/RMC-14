    private void OnToolChanged(TacticalMapToolKind kind)
    {
        Map.Tool = kind switch
        {
            TacticalMapToolKind.Pen => new TacticalMapPenTool(),
            TacticalMapToolKind.Line => new TacticalMapLineTool(),
            TacticalMapToolKind.Rectangle => new TacticalMapRectangleTool(),
            TacticalMapToolKind.Eraser => new TacticalMapEraserTool(),
            TacticalMapToolKind.Label => new TacticalMapLabelTool(),
            _ => null,
        };

        if (kind == TacticalMapToolKind.Label && !Map.LabelsEnabled)
            ToggleLabels();

        UpdateModeLabel();
    }

    private void OnColorChanged(int index)
    {
        Map.DrawColor = TacticalMapToolPanel.Palette[index].Color;
        _settings.ColorIndex = index;
    }

