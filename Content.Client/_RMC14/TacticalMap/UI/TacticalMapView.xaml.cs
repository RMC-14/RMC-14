    public void SetDrawing(bool drawing, EntityUid? drawTarget, TacticalMapCanvasDraft? draft, TacticalMapCanvasLayer? drawLayer)
    {
        _drawing = drawing;
        _drawLayer = drawLayer;
        if (!drawing)
        {
            Map.Tool = null;
            ToolPanel.SetTool(TacticalMapToolKind.None);
        }

        Map.SetDraft(draft);
        ToolPanel.SetDrawTargets(_layers, drawTarget);
        UpdateModeLabel();
        UpdatePanels();
    }

    public void SetObjectives(IReadOnlyDictionary<SquadObjectiveType, string>? objectives)
    {
        ObjectivesList.RemoveAllChildren();
        _hasObjectives = objectives != null && objectives.Values.Any(o => !string.IsNullOrWhiteSpace(o));
        if (_hasObjectives)
        {
            foreach (var type in Enum.GetValues<SquadObjectiveType>())
            {
                var text = objectives!.GetValueOrDefault(type, string.Empty);
                var name = type switch
                {
                    SquadObjectiveType.Primary => Loc.GetString("rmc-overwatch-console-objective-primary"),
                    SquadObjectiveType.Secondary => Loc.GetString("rmc-overwatch-console-objective-secondary"),
                    _ => type.ToString(),
                };

                var empty = string.IsNullOrWhiteSpace(text);
                var entry = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Vertical,
                    SeparationOverride = 1,
                };

                entry.AddChild(new TacticalMapLabel
                {
                    Text = name.ToUpperInvariant(),
                    TextStyle = TacticalMapTextStyle.Heading,
                });

                var label = new RichTextLabel { HorizontalExpand = true };
                label.SetMessage(
                    FormattedMessage.FromUnformatted(empty ? Loc.GetString("rmc-squad-info-none") : text),
                    defaultColor: empty ? _theme.TextMuted : _theme.Text);

                entry.AddChild(label);
                ObjectivesList.AddChild(entry);
            }

            TacticalMapStyle.ApplyTheme(ObjectivesList, _theme);
        }

        UpdateButtons();
        UpdatePanels();
    }

