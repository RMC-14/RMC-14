        MapSelectButton.OnItemSelected += args =>
        {
            if (_suppressMapSelection || args.Id < 0 || args.Id >= _maps.Count)
                return;

            MapSelectButton.SelectId(args.Id);
            SelectMap(_maps[args.Id].Map, true);
        };

        LayerPanel.VisibilityToggled += channel => LayerVisibilityToggled?.Invoke(channel);

        ToolPanel.SubmitPressed += () => SubmitPressed?.Invoke();
        ToolPanel.ClearPressed += () => ClearPressed?.Invoke();
        ToolPanel.UndoPressed += () => UndoPressed?.Invoke();
        ToolPanel.DrawTargetSelected += channel => DrawTargetSelected?.Invoke(channel);
        ToolPanel.ToolChanged += OnToolChanged;
        ToolPanel.ColorChanged += OnColorChanged;
        ToolPanel.ThicknessChanged += OnThicknessChanged;

        OverlayPanel.OverlaysChanged += overlays => Map.Overlays = overlays;

        LabelsButton.OnPressed += _ => ToggleLabels();
        LabelModeAllButton.OnPressed += _ => SetLabelMode(TacticalMapLabelMode.All);
        LabelModeTacticalButton.OnPressed += _ => SetLabelMode(TacticalMapLabelMode.Tactical);
        LabelModeAreaButton.OnPressed += _ => SetLabelMode(TacticalMapLabelMode.Area);
        FollowButton.OnPressed += _ => ToggleFollow();
        ResetViewButton.OnPressed += _ => ResetView();
        LayersButton.OnPressed += _ => ToggleLayers();
        OverlaysButton.OnPressed += _ => ToggleOverlays();
        ObjectivesButton.OnPressed += _ => ToggleObjectives();
        SettingsButton.OnPressed += _ => ToggleDisplay();
        FocusButton.OnPressed += _ => ToggleFocus();
        PopoutButton.OnPressed += _ => PopoutRequested?.Invoke();
        CloseButton.OnPressed += _ => CloseRequested?.Invoke();
        CrtButton.OnPressed += _ => ToggleCrt();
        BlipSizeSlider.OnValueChanged += args =>
        {
            Map.BlipSizeMultiplier = args.Value;
            _settings.BlipSize = args.Value;
            UpdateBlipSizeLabel();
        };

        LoadSettings();
        LoadPreviewRanges();
        RegisterCompactButtons();
