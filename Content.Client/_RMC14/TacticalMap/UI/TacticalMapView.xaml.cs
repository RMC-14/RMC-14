    public void SetMaps(IReadOnlyList<TacticalMapMapOption> maps, EntityUid? preferred)
    {
        var changed = maps.Count != _maps.Count;
        for (var i = 0; !changed && i < maps.Count; i++)
        {
            changed = maps[i] != _maps[i];
        }

        if (changed)
        {
            _suppressMapSelection = true;
            _maps.Clear();
            _maps.AddRange(maps);
            MapSelectButton.Clear();
            for (var i = 0; i < _maps.Count; i++)
            {
                MapSelectButton.AddItem(_maps[i].Name, i);
            }

            _suppressMapSelection = false;
        }

        MapSelectButton.Visible = _maps.Count > 1;

        // keep the current map, else the one the viewer is on, else the first
        EntityUid? selected = null;
        if (_selectedMap is { } current && _maps.Any(m => m.Map == current))
            selected = current;
        else if (preferred is { } wanted && _maps.Any(m => m.Map == wanted))
            selected = wanted;
        else if (_maps.Count > 0)
            selected = _maps[0].Map;

        if (selected is { } map)
        {
            var index = _maps.FindIndex(m => m.Map == map);
            if (index >= 0 && MapSelectButton.SelectedId != index)
            {
                _suppressMapSelection = true;
                MapSelectButton.SelectId(index);
                _suppressMapSelection = false;
            }
        }

        SelectMap(selected, false);
    }

    private void SelectMap(EntityUid? map, bool fromUser)
    {
        if (_selectedMap == map)
            return;

        SaveViewState();
        _selectedMap = map;
        Map.ClearMortarMarker();
        Map.SetBaseMap(map);
        LoadViewState();

        if (fromUser && map != null)
            MapSelected?.Invoke(map.Value);
    }

    public void SetBlips(
        IReadOnlyList<TacticalMapBlipView> blips,
        NetEntity? self,
        Vector2i? selfIndices,
        TacticalMapBlip? selfBlip,
        bool live,
        TimeSpan? snapshotAt)
    {
        Map.SetBlips(blips);
        Map.SetSelf(self, selfIndices, selfBlip);

        if (_live == live && _snapshotAt == snapshotAt)
            return;

        _live = live;
        _snapshotAt = snapshotAt;
        UpdateFeedLabel();
    }

