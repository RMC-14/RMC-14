using System.Linq;
using Content.Client.Options.UI;
using Content.Shared._RMC14.Announce;
using Content.Shared._RMC14.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;

namespace Content.Client._RMC14.Announce;

[GenerateTypedNameReferences]
public sealed partial class RMCAnnouncementOptions : BoxContainer
{
    [Dependency] private readonly IConfigurationManager _cfg = default!;

    public RMCAnnouncementOptions()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void Register(OptionsTabControlRow row)
    {
        row.AddOptionDropDown(
            RMCCVars.RMCAnnouncementMode,
            ModeDropDown,
            new[]
            {
                new OptionDropDownCVar<RMCAnnouncementDisplayMode>.ValueOption(
                    RMCAnnouncementDisplayMode.Full,
                    Loc.GetString("rmc-ui-options-announcements-style-stylized")),
                new OptionDropDownCVar<RMCAnnouncementDisplayMode>.ValueOption(
                    RMCAnnouncementDisplayMode.Simple,
                    Loc.GetString("rmc-ui-options-announcements-style-simplified")),
                new OptionDropDownCVar<RMCAnnouncementDisplayMode>.ValueOption(
                    RMCAnnouncementDisplayMode.Off,
                    Loc.GetString("rmc-ui-options-announcements-style-disabled")),
            });

        row.AddOptionSlider(
            RMCCVars.RMCAnnouncementMaxVisible,
            MaxVisibleSlider,
            RMCAnnouncementUIController.MinVisible,
            RMCAnnouncementUIController.MaxVisible);

        var announcements = UserInterfaceManager.GetUIController<RMCAnnouncementUIController>();
        foreach (var group in announcements.GetSettingsGroups().OrderBy(group => group.Name))
        {
            var dropDown = new OptionDropDown { Title = group.Name };
            GroupsContainer.AddChild(dropDown);
            row.AddOption(new GroupModeOption(row, _cfg, dropDown, group.Id));
        }

        var layout = UserInterfaceManager.GetUIController<RMCAnnouncementLayoutUIController>();
        EditLayoutButton.OnPressed += _ =>
        {
            if (!layout.TryOpen())
                return;

            var parent = Parent;
            while (parent != null && parent is not BaseWindow)
            {
                parent = parent.Parent;
            }

            (parent as BaseWindow)?.Close();
        };

        ResetLayoutButton.OnPressed += _ => layout.ResetAll();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _cfg.OnValueChanged(RMCCVars.RMCAnnouncementOverrides, UpdateLayoutSummary, true);
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _cfg.UnsubValueChanged(RMCCVars.RMCAnnouncementOverrides, UpdateLayoutSummary);
    }

    private void UpdateLayoutSummary(string serialized)
    {
        var overrides = RMCAnnouncementOverrides.Parse(serialized);
        var global = overrides.GetValueOrDefault(RMCAnnouncementOverrides.GlobalKey).HasLayout;
        var count = overrides.Count(pair => pair.Key != RMCAnnouncementOverrides.GlobalKey && pair.Value.HasLayout);

        LayoutSummaryLabel.Text = Loc.GetString(
            "rmc-ui-options-announcements-layout-summary",
            ("global", Loc.GetString(global
                ? "rmc-ui-options-announcements-layout-summary-custom"
                : "rmc-ui-options-announcements-layout-summary-default")),
            ("count", count));
    }

    private sealed class GroupModeOption : BaseOption
    {
        private const int DefaultId = -1;

        private readonly IConfigurationManager _cfg;
        private readonly OptionDropDown _dropDown;
        private readonly string _groupId;

        public GroupModeOption(
            OptionsTabControlRow controller,
            IConfigurationManager cfg,
            OptionDropDown dropDown,
            string groupId) : base(controller)
        {
            _cfg = cfg;
            _dropDown = dropDown;
            _groupId = groupId;

            _dropDown.Button.AddItem(Loc.GetString("rmc-ui-options-announcements-style-default"), DefaultId);
            _dropDown.Button.AddItem(Loc.GetString("rmc-ui-options-announcements-style-stylized"), (int) RMCAnnouncementDisplayMode.Full);
            _dropDown.Button.AddItem(Loc.GetString("rmc-ui-options-announcements-style-simplified"), (int) RMCAnnouncementDisplayMode.Simple);
            _dropDown.Button.AddItem(Loc.GetString("rmc-ui-options-announcements-style-disabled"), (int) RMCAnnouncementDisplayMode.Off);
            _dropDown.Button.OnItemSelected += args =>
            {
                _dropDown.Button.SelectId(args.Id);
                ValueChanged();
            };
        }

        private RMCAnnouncementDisplayMode? Selected
        {
            get => _dropDown.Button.SelectedId == DefaultId ? null : (RMCAnnouncementDisplayMode) _dropDown.Button.SelectedId;
            set => _dropDown.Button.SelectId(value is { } mode ? (int) mode : DefaultId);
        }

        private RMCAnnouncementDisplayMode? Stored =>
            RMCAnnouncementOverrides.Parse(_cfg.GetCVar(RMCCVars.RMCAnnouncementOverrides)).GetValueOrDefault(_groupId).Mode;

        public override void LoadValue()
        {
            Selected = Stored;
        }

        public override void SaveValue()
        {
            var overrides = RMCAnnouncementOverrides.Parse(_cfg.GetCVar(RMCCVars.RMCAnnouncementOverrides));
            overrides[_groupId] = overrides.GetValueOrDefault(_groupId) with { Mode = Selected };
            _cfg.SetCVar(RMCCVars.RMCAnnouncementOverrides, RMCAnnouncementOverrides.Serialize(overrides));
        }

        public override void ResetToDefault()
        {
            Selected = null;
        }

        public override bool IsModified()
        {
            return Selected != Stored;
        }

        public override bool IsModifiedFromDefault()
        {
            return Selected != null;
        }
    }
}
