using System.Linq;
using Content.Client.Options.UI;
using Content.Shared._RMC14.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;

namespace Content.Client._RMC14.Announce;

[GenerateTypedNameReferences]
public sealed partial class RMCAnnouncementOptions : BoxContainer
{
    [Dependency] private readonly IConfigurationManager _cfg = default!;

    public RMCAnnouncementOptions()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void Register(OptionsTabControlRow row)
    {
        row.AddOptionSlider(
            RMCCVars.RMCAnnouncementMaxVisible,
            MaxVisibleSlider,
            RMCAnnouncementUIController.MinVisible,
            RMCAnnouncementUIController.MaxVisible);

        var layout = UserInterfaceManager.GetUIController<RMCAnnouncementLayoutUIController>();
        EditLayoutButton.OnPressed += _ =>
        {
            if (!layout.TryOpen())
                return;

            var parent = Parent;
            while (parent != null && parent is not BaseWindow)
            {
                parent = parent.Parent;
            }

            (parent as BaseWindow)?.Close();
        };

        ResetLayoutButton.OnPressed += _ => layout.ResetAll();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _cfg.OnValueChanged(RMCCVars.RMCAnnouncementOverrides, UpdateLayoutSummary, true);
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _cfg.UnsubValueChanged(RMCCVars.RMCAnnouncementOverrides, UpdateLayoutSummary);
    }

    private void UpdateLayoutSummary(string serialized)
    {
        var overrides = RMCAnnouncementOverrides.Parse(serialized);
        var global = overrides.GetValueOrDefault(RMCAnnouncementOverrides.GlobalKey).HasLayout;
        var count = overrides.Count(pair => pair.Key != RMCAnnouncementOverrides.GlobalKey && pair.Value.HasLayout);

        LayoutSummaryLabel.Text = Loc.GetString(
            "rmc-ui-options-announcements-layout-summary",
            ("global", Loc.GetString(global
                ? "rmc-ui-options-announcements-layout-summary-custom"
                : "rmc-ui-options-announcements-layout-summary-default")),
            ("count", count));
    }
}
