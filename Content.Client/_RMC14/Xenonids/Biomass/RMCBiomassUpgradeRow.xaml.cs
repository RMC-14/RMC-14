using Content.Client._RMC14.UserInterface;
using Content.Shared._RMC14.Xenonids.Biomass;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using static Content.Client._RMC14.UserInterface.RMCMachineUiStyle;

namespace Content.Client._RMC14.Xenonids.Biomass;

[GenerateTypedNameReferences]
public sealed partial class RMCBiomassUpgradeRow : PanelContainer
{
    private static readonly Color LockedTint = new(1f, 1f, 1f, 0.5f);
    private static readonly Color AlternateColor = Color.Black.WithAlpha(0.15f);
    private static readonly Color HoverColor = Color.White.WithAlpha(0.05f);

    public EntProtoId<RMCBiomassUpgradeComponent>? UpgradeId;
    public Action<EntProtoId<RMCBiomassUpgradeComponent>, int>? OnPrint;

    private readonly RMCMachineButton[] _printButtons;
    private readonly StyleBoxFlat _background = new();
    private bool _alternate;
    private bool _hovered;

    public RMCBiomassUpgradeRow()
    {
        RobustXamlLoader.Load(this);

        PanelOverride = _background;
        _printButtons = [PrintButton, Print2Button, Print5Button, Print10Button];
        PrintButton.SetIcon(RMCIcons.Print, "Print");

        PrintButton.OnPressed += _ => Print(1);
        Print2Button.OnPressed += _ => Print(2);
        Print5Button.OnPressed += _ => Print(5);
        Print10Button.OnPressed += _ => Print(10);
    }

    public void SetItem(EntProtoId item)
    {
        ItemView.SetPrototype(item);
    }

    public void SetAlternate(bool alternate)
    {
        _alternate = alternate;
        UpdateBackground();
    }

    public void SetDescription(string description)
    {
        foreach (var button in _printButtons)
        {
            button.ToolTip = description;
        }
    }

    public void SetCost(int cost, bool affordable)
    {
        CostLabel.Text = $"Cost: {cost}";
        CostLabel.FontColorOverride = affordable ? Color.White : CautionTextColor;
    }

    public void SetTrend(int priceChange)
    {
        (TrendLabel.Text, TrendLabel.FontColorOverride) = priceChange switch
        {
            0 => ("Fixed price.", LabelColor),
            > 0 => ($"Cost rises by {priceChange} each purchase.", AverageColor),
            _ => ($"Cost falls by {-priceChange} each purchase.", GoodColor),
        };
    }

    public void SetClearance(string tierName, bool met)
    {
        ClearanceLabel.Text = $"Clearance {tierName} Required";
        ClearanceLabel.FontColorOverride = LabelColor;
        ClearancePanel.Visible = !met;

        var tint = met ? Color.White : LockedTint;
        NameColumn.Modulate = tint;
        CostLabel.Modulate = tint;
        TrendLabel.Modulate = tint;
        PrintColumn.Modulate = tint;

        foreach (var button in _printButtons)
        {
            button.Disabled = !met;
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        var hovered = false;
        for (var control = UserInterfaceManager.CurrentlyHovered; control != null; control = control.Parent)
        {
            if (control != this)
                continue;

            hovered = true;
            break;
        }

        if (hovered == _hovered)
            return;

        _hovered = hovered;
        UpdateBackground();
    }

    private void UpdateBackground()
    {
        _background.BackgroundColor = _hovered
            ? HoverColor
            : _alternate ? AlternateColor : Color.Transparent;
    }

    private void Print(int amount)
    {
        if (UpgradeId is { } id)
            OnPrint?.Invoke(id, amount);
    }
}
