using Content.Client._RMC14.UserInterface;
using Content.Client.Resources;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using static Content.Client._RMC14.UserInterface.RMCMachineUiStyle;

namespace Content.Client._RMC14.Xenonids.Biomass;

[GenerateTypedNameReferences]
public sealed partial class RMCBiomassAnalyzerWindow : DefaultWindow
{
    public readonly RMCIconLabelRow EjectOrganIcon;
    public readonly RMCIconLabelRow ProcessOrganIcon;
    public readonly RMCIconLabelRow AutoProcessIcon;
    public readonly RMCIconLabelRow ToggleQueueIcon;

    private readonly Font _noticeFont;

    public RMCBiomassAnalyzerWindow()
    {
        RobustXamlLoader.Load(this);
        RemoveWindowBorder(this);

        _noticeFont = IoCManager.Resolve<IResourceCache>().GetFont("/Fonts/NotoSans/NotoSans-Bold.ttf", 12);

        EjectOrganIcon = EjectOrganButton.SetIcon(RMCIcons.Eject, "Eject Biomass");
        ProcessOrganIcon = ProcessOrganButton.SetIcon(RMCIcons.Flask, "Process Biomass");
        AutoProcessIcon = AutoProcessButton.SetIcon(RMCIcons.ArrowsRotate, "Auto: OFF");
        ToggleQueueIcon = ToggleQueueButton.SetIcon(RMCIcons.Play, "START");

        AutoProcessButton.ToolTip = "Automatically start the queue when biomass is inserted.";
    }

    public void SetPoints(int points)
    {
        Notice(PointsPanel, PointsLabel, $"Biological Matter: {points}", NoticeColor, _noticeFont);
    }
}
