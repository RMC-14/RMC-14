using Content.Client._RMC14.UserInterface;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using static Content.Client._RMC14.Xenonids.Biomass.RMCBiomassAnalyzerColors;

namespace Content.Client._RMC14.Xenonids.Biomass;

[GenerateTypedNameReferences]
public sealed partial class RMCBiomassAnalyzerWindow : DefaultWindow
{
    public readonly RMCIconLabelRow EjectOrganIcon;
    public readonly RMCIconLabelRow ProcessOrganIcon;
    public readonly RMCIconLabelRow AutoProcessIcon;
    public readonly RMCIconLabelRow ToggleQueueIcon;

    public RMCBiomassAnalyzerWindow()
    {
        RobustXamlLoader.Load(this);

        EjectOrganIcon = Icon(EjectOrganButton, RMCIcons.Eject, "Eject Biomass");
        ProcessOrganIcon = Icon(ProcessOrganButton, RMCIcons.Flask, "Process Biomass");
        AutoProcessIcon = Icon(AutoProcessButton, RMCIcons.ArrowsRotate, "Auto: OFF");
        ToggleQueueIcon = Icon(ToggleQueueButton, RMCIcons.Play, "START");

        AutoProcessButton.ToolTip = "Automatically start the queue when biomass is inserted.";
    }

    public static void SetButtonEnabled(Button button, bool enabled)
    {
        button.Disabled = !enabled;
        button.Modulate = enabled ? Color.White : DisabledTint;
    }

    private static RMCIconLabelRow Icon(Button button, string texturePath, string text)
    {
        return button.AddIconLabel(texturePath, text, alignment: Control.HAlignment.Center, fontColor: AmberBlack);
    }
}
