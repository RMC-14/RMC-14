using System;
using Content.Client._RMC14.UserInterface;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._RMC14.Xenonids.Biomass;

[GenerateTypedNameReferences]
public sealed partial class RMCBiomassAnalyzerWindow : DefaultWindow
{
    public static readonly Color Amber = Color.FromHex("#FFD21A");
    public static readonly Color AmberDim = Color.FromHex("#8A6800");
    public static readonly Color AmberBlack = Color.FromHex("#150E00");

    public readonly RMCIconLabelRow ProcessOrganIcon;
    public readonly RMCIconLabelRow ToggleQueueIcon;

    public RMCBiomassAnalyzerWindow()
    {
        RobustXamlLoader.Load(this);

        Icon(EjectOrganButton, RMCIcons.Eject, "Eject Biomass");
        ProcessOrganIcon = Icon(ProcessOrganButton, RMCIcons.Flask, "Auto: OFF");
        ToggleQueueIcon = Icon(ToggleQueueButton, RMCIcons.Play, "START");
    }

    private static RMCIconLabelRow Icon(Button button, string texturePath, string text)
    {
        return button.AddIconLabel(texturePath, text, alignment: Control.HAlignment.Center, fontColor: AmberBlack);
    }
}
