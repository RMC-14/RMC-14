using Content.Client._RMC14.TacticalMap.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.Xenonids.Construction.Tunnel;

[GenerateTypedNameReferences]
public sealed partial class SelectDestinationTunnelPanel : BoxContainer
{
    private readonly List<(NetEntity Tunnel, TacticalMapButton Button)> _buttons = new();

    public event Action<NetEntity>? TunnelSelected;
    public event Action? TravelPressed;
    public event Action? OnlyTunnelsToggled;

    public SelectDestinationTunnelPanel()
    {
        RobustXamlLoader.Load(this);
        TravelButton.OnPressed += _ => TravelPressed?.Invoke();
        OnlyTunnelsButton.OnPressed += _ => OnlyTunnelsToggled?.Invoke();
    }

    public void SetTunnels(IEnumerable<(string Name, NetEntity Tunnel)> tunnels)
    {
        TunnelList.RemoveAllChildren();
        _buttons.Clear();
        foreach (var (name, tunnel) in tunnels)
        {
            var button = new TacticalMapButton
            {
                Text = name,
                AlignLeft = true,
                HorizontalExpand = true,
                MinHeight = 22,
            };

            button.OnPressed += _ => TunnelSelected?.Invoke(tunnel);
            _buttons.Add((tunnel, button));
            TunnelList.AddChild(button);
        }

        EmptyLabel.Visible = _buttons.Count == 0;
        TacticalMapStyle.ApplyTheme(this, TacticalMapTheme.Xeno);
    }

    public void SetState(string? current, string? selected, NetEntity? selectedTunnel, bool onlyTunnels)
    {
        CurrentLabel.Text = Loc.GetString("xeno-ui-tunnel-current", ("name", current ?? Loc.GetString("xeno-ui-tunnel-unknown")));
        SelectedLabel.Text = selected == null
            ? Loc.GetString("xeno-ui-tunnel-no-destination")
            : Loc.GetString("xeno-ui-tunnel-destination", ("name", selected));

        SelectedLabel.ToolTip = SelectedLabel.Text;
        CurrentLabel.ToolTip = CurrentLabel.Text;
        TravelButton.Disabled = selectedTunnel == null;
        OnlyTunnelsButton.Active = onlyTunnels;

        foreach (var (tunnel, button) in _buttons)
        {
            button.Active = tunnel == selectedTunnel;
        }
    }
}
