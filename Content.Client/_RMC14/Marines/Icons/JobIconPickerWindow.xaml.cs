using System.Numerics;
using Content.Client.Stylesheets;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._RMC14.Marines.Icons;

[GenerateTypedNameReferences]
public sealed partial class JobIconPickerWindow : DefaultWindow
{
    [Dependency] private readonly IResourceCache _resourceCache = default!;
    [Dependency] private readonly IEntitySystemManager _entitySystem = default!;

    private static readonly ResPath TextureRoot = new("/Textures");
    private static readonly ResPath JobIconsRoot = new("/Textures/_RMC14/Interface/job_icons");

    private readonly SpriteSystem _sprite;
    private readonly List<(ResPath Rsi, string State)> _allIcons = new();

    public event Action<ResPath, string>? OnIconSelected;
    public event Action? OnClear;

    public JobIconPickerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprite = _entitySystem.GetEntitySystem<SpriteSystem>();

        SearchBar.OnTextChanged += args => BuildGrid(args.Text);
        ClearButton.OnPressed += _ => OnClear?.Invoke();
    }

    public void Populate()
    {
        if (_allIcons.Count == 0)
            _allIcons.AddRange(GetIcons());

        BuildGrid(SearchBar.Text);
    }

    private void BuildGrid(string filter)
    {
        IconGrid.RemoveAllChildren();

        foreach (var (rsi, state) in _allIcons)
        {
            if (!string.IsNullOrWhiteSpace(filter) &&
                !state.Contains(filter.Trim(), StringComparison.OrdinalIgnoreCase))
            {
                continue;
            }

            var specifier = new SpriteSpecifier.Rsi(rsi, state);
            var button = new Button
            {
                StyleClasses = { StyleBase.ButtonSquare },
                MaxSize = new Vector2(42, 42),
                ToolTip = state,
            };

            button.AddChild(new TextureRect
            {
                Texture = _sprite.Frame0(specifier),
                TextureScale = new Vector2(2f, 2f),
                Stretch = TextureRect.StretchMode.KeepCentered,
            });

            var capturedRsi = rsi;
            var capturedState = state;
            button.OnPressed += _ => OnIconSelected?.Invoke(capturedRsi, capturedState);

            IconGrid.AddChild(button);
        }
    }

    private List<(ResPath Rsi, string State)> GetIcons()
    {
        var icons = new List<(ResPath Rsi, string State)>();
        foreach (var file in _resourceCache.ContentFindFiles(JobIconsRoot))
        {
            if (file.Filename != "meta.json")
                continue;

            var rsiDir = file.Directory;
            if (!_resourceCache.TryGetResource<RSIResource>(rsiDir, out var rsiRes))
                continue;

            if (!rsiDir.TryRelativeTo(TextureRoot, out var relative))
                continue;

            foreach (var state in rsiRes.RSI)
            {
                if (state.StateId.Name is { } name)
                    icons.Add((relative.Value, name));
            }
        }

        icons.Sort((a, b) => string.Compare(a.State, b.State, StringComparison.Ordinal));
        return icons;
    }
}
