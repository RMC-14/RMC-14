using System.Numerics;
using Content.Client.Lobby;
using Content.Client.Players.PlayTimeTracking;
using Content.Shared._RMC14.FaxResponder;
using Content.Shared.Preferences;
using Content.Shared.Roles;
using Content.Shared.StatusIcon;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Network;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._RMC14.Lobby;

[GenerateTypedNameReferences]
public sealed partial class JoinFaxResponderWindow : DefaultWindow
{
    [Dependency] private readonly IEntityManager _entManager = default!;
    [Dependency] private readonly JobRequirementsManager _jobRequirements = default!;
    [Dependency] private readonly INetManager _net = default!;
    [Dependency] private readonly IClientPreferencesManager _preferencesManager = default!;
    [Dependency] private readonly IPrototypeManager _prototypes = default!;

    private readonly Dictionary<string, JobButton> _jobButtons = new();

    public JoinFaxResponderWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _net.RegisterNetMessage<FaxResponderStatusEvent>(OnFaxResponderStatus);
        _jobRequirements.Updated += RebuildUI;

        RebuildUI();
        RequestFaxResponderStatus();
    }

    private void OnFaxResponderStatus(FaxResponderStatusEvent ev)
    {
        UpdateSlots("CMWeYaresponder", ev.WeyaSlots);
        UpdateSlots("CMFreePressResponder", ev.FreePressSlots);
    }

    private void UpdateSlots(string jobId, int slots)
    {
        if (_jobButtons.TryGetValue(jobId, out var button))
        {
            button.RefreshLabel(slots);
            // Only disable for slots if not already disabled by whitelist
            if (!button.LockedByWhitelist)
                button.Disabled = slots <= 0;
        }
    }

    private void RebuildUI()
    {
        JobList.RemoveAllChildren();
        _jobButtons.Clear();

        var sprites = _entManager.System<SpriteSystem>();

        AddJobButton(sprites, "CMWeYaresponder", "CMJobIconWeYa");
        AddJobButton(sprites, "CMFreePressResponder", "CMJobIconReporter");
    }

    private void AddJobButton(SpriteSystem sprites, string jobId, string iconId)
    {
        if (!_prototypes.TryIndex<JobPrototype>(jobId, out var jobPrototype))
            return;

        var name = jobPrototype.LocalizedName;
        var jobLabel = new Label { Margin = new Thickness(5f, 0, 0, 0) };
        var jobButton = new JobButton(jobLabel, jobId, name, null);

        var jobSelector = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true
        };

        if (_prototypes.TryIndex<JobIconPrototype>(iconId, out var jobIcon))
        {
            var icon = new TextureRect
            {
                TextureScale = new Vector2(2, 2),
                VerticalAlignment = VAlignment.Center,
                Texture = sprites.Frame0(jobIcon.Icon)
            };
            jobSelector.AddChild(icon);
        }

        jobSelector.AddChild(jobLabel);
        jobButton.AddChild(jobSelector);

        jobButton.OnPressed += _ =>
        {
            var ev = new JoinFaxResponderRequest(jobId);
            _entManager.EntityNetManager?.SendSystemNetworkMessage(ev);
            Close();
        };

        // Check whitelist
        if (!_jobRequirements.IsAllowed(jobPrototype, (HumanoidCharacterProfile?)_preferencesManager.Preferences?.SelectedCharacter, out var reason))
        {
            jobButton.Disabled = true;
            jobButton.LockedByWhitelist = true;

            if (!reason.IsEmpty)
            {
                var tooltip = new Tooltip();
                tooltip.SetMessage(reason);
                jobButton.TooltipSupplier = _ => tooltip;
            }

            jobSelector.AddChild(new TextureRect
            {
                TextureScale = new Vector2(0.4f, 0.4f),
                Stretch = TextureRect.StretchMode.KeepCentered,
                Texture = sprites.Frame0(new SpriteSpecifier.Texture(new("/Textures/Interface/Nano/lock.svg.192dpi.png"))),
                HorizontalExpand = true,
                HorizontalAlignment = HAlignment.Right,
            });
        }

        JobList.AddChild(jobButton);
        _jobButtons[jobId] = jobButton;
    }

    private void RequestFaxResponderStatus()
    {
        var ev = new FaxResponderStatusRequest();
        _entManager.EntityNetManager?.SendSystemNetworkMessage(ev);
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (disposing)
        {
            _jobRequirements.Updated -= RebuildUI;
        }
    }

    private sealed class JobButton : ContainerButton
    {
        public Label JobLabel { get; }
        public string JobId { get; }
        public string JobLocalisedName { get; }
        public int? Amount { get; private set; }
        public bool LockedByWhitelist { get; set; }

        public JobButton(Label jobLabel, string jobId, string jobLocalisedName, int? amount)
        {
            JobLabel = jobLabel;
            JobId = jobId;
            JobLocalisedName = jobLocalisedName;
            RefreshLabel(amount);
            AddStyleClass(StyleClassButton);
        }

        public void RefreshLabel(int? amount)
        {
            Amount = amount;
            JobLabel.Text = Amount != null
                ? Loc.GetString("late-join-gui-job-slot-capped", ("jobName", JobLocalisedName), ("amount", Amount))
                : Loc.GetString("late-join-gui-job-slot-uncapped", ("jobName", JobLocalisedName));
        }
    }
}
