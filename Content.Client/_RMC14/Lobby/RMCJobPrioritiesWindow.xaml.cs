[GenerateTypedNameReferences]
public sealed partial class RMCJobPrioritiesWindow : DefaultWindow
{
    [Dependency] private readonly IEntityManager _entity = default!;
    [Dependency] private readonly IClientPreferencesManager _preferences = default!;
    [Dependency] private readonly IPrototypeManager _prototype = default!;
    [Dependency] private readonly JobRequirementsManager _requirements = default!;

    private const float MinColumnWidth = 230;
    private const float ColumnSeparation = 6;
    private const float PriorityWidth = 52;

    public static readonly Color HighColor = Color.FromHex("#E0B84C");
    public static readonly Color MediumColor = Color.FromHex("#4FA3D9");
    public static readonly Color LowColor = Color.FromHex("#8A97A3");
    private static readonly Color NeverColor = Color.FromHex("#5C5C66");
    private static readonly Color LockedColor = Color.FromHex("#6B6B6B");
    private static readonly Color HeaderBase = Color.FromHex("#1B1B1E");

    private readonly List<(DepartmentPrototype Department, List<JobPrototype> Jobs)> _departments = new();
    private readonly List<Control> _departmentControls = new();
    private Dictionary<ProtoId<JobPrototype>, JobPriority> _priorities = new();
    private RMCPlayerSettings _settings = RMCPlayerSettings.Default;
    private int _columns;

    public event Action<Dictionary<ProtoId<JobPrototype>, JobPriority>>? PrioritiesChanged;
    public event Action<RMCPlayerSettings>? SettingsChanged;

    public RMCJobPrioritiesWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        SearchLineEdit.OnTextChanged += _ => Rebuild();
        SelectedOnlyCheck.OnToggled += _ => Rebuild();
        ColumnBox.OnResized += () =>
        {
            if (GetColumnCount() != _columns)
                UserInterfaceManager.DeferAction(Distribute);
        };

        PreferenceUnavailableButton.AddItem(
            Loc.GetString("rmc-job-priorities-window-unavailable-lobby"),
            (int) PreferenceUnavailableMode.StayInLobby);
        PreferenceUnavailableButton.AddItem(
            Loc.GetString("rmc-job-priorities-window-unavailable-overflow",
                ("overflowJob", Loc.GetString(SharedGameTicker.FallbackOverflowJobName))),
            (int) PreferenceUnavailableMode.SpawnAsOverflow);

        PreferenceUnavailableButton.OnItemSelected += args =>
        {
            PreferenceUnavailableButton.SelectId(args.Id);
            CommitSettings(_settings with { PreferenceUnavailable = (PreferenceUnavailableMode) args.Id });
        };
        PlaytimePerksButton.OnToggled += args => CommitSettings(_settings with { PlaytimePerks = args.Pressed });
        XenoPrefix.OnTextEntered += _ => CommitXenoName();
        XenoPrefix.OnFocusExit += _ => CommitXenoName();
        XenoPostfix.OnTextEntered += _ => CommitXenoName();
        XenoPostfix.OnFocusExit += _ => CommitXenoName();

        Refresh();
    }

    public void Refresh()
    {
        _priorities = _preferences.Preferences?.JobPriorities.ToDictionary() ?? new Dictionary<ProtoId<JobPrototype>, JobPriority>();
        RefreshDepartments();
        RefreshSettings();
        Rebuild();
    }

    private void RefreshDepartments()
    {
        _departments.Clear();
        var departments = _prototype.EnumerateCM<DepartmentPrototype>()
            .Where(d => !d.Hidden && !d.EditorHidden)
            .ToList();
        departments.Sort(DepartmentUIComparer.Instance);

        foreach (var department in departments)
        {
            var jobs = new List<JobPrototype>();
            foreach (var id in department.Roles.Distinct())
            {
                if (!_prototype.TryIndex(id, out var job) || !job.IsCM || job.Hidden || !job.SetPreference)
                    continue;

                jobs.Add(job);
            }

            jobs.Sort(JobUIComparer.Instance);
            if (jobs.Count > 0)
                _departments.Add((department, jobs));
        }
    }

    private void RefreshSettings()
    {
        _settings = _preferences.Preferences?.PlayerSettings ?? RMCPlayerSettings.Default;
        PreferenceUnavailableButton.SelectId((int) _settings.PreferenceUnavailable);
        PlaytimePerksButton.Pressed = _settings.PlaytimePerks;

        if (!XenoPrefix.HasKeyboardFocus())
            XenoPrefix.Text = _settings.XenoPrefix;

        if (!XenoPostfix.HasKeyboardFocus())
            XenoPostfix.Text = _settings.XenoPostfix;
    }

    private void CommitXenoName()
    {
        CommitSettings(_settings with { XenoPrefix = XenoPrefix.Text, XenoPostfix = XenoPostfix.Text });
    }

    private void CommitSettings(RMCPlayerSettings settings)
    {
        if (settings == _settings)
            return;

        SettingsChanged?.Invoke(settings);
        _settings = _preferences.Preferences?.PlayerSettings ?? settings;
        PreferenceUnavailableButton.SelectId((int) _settings.PreferenceUnavailable);
        PlaytimePerksButton.Pressed = _settings.PlaytimePerks;
        XenoPrefix.Text = _settings.XenoPrefix;
        XenoPostfix.Text = _settings.XenoPostfix;
    }

    private void Rebuild()
    {
        _departmentControls.Clear();
        var search = SearchLineEdit.Text.Trim();
        var selectedOnly = SelectedOnlyCheck.Pressed;

        foreach (var (department, jobs) in _departments)
        {
            var departmentMatches = search.Length > 0 &&
                                    Loc.GetString(department.Name).Contains(search, StringComparison.CurrentCultureIgnoreCase);
            var shown = jobs.Where(job =>
                    (!selectedOnly || GetPriority(job.ID) != JobPriority.Never) &&
                    (search.Length == 0 || departmentMatches ||
                     job.LocalizedName.Contains(search, StringComparison.CurrentCultureIgnoreCase)))
                .ToList();

            if (shown.Count == 0)
                continue;

            _departmentControls.Add(BuildDepartment(department, jobs, shown));
        }

        Distribute();
    }

    private int GetColumnCount()
    {
        var width = ColumnBox.Width > 0 ? ColumnBox.Width : SetWidth;
        if (float.IsNaN(width) || width <= 0)
            return 1;

        return Math.Max(1, (int) ((width + ColumnSeparation) / (MinColumnWidth + ColumnSeparation)));
    }

    private void Distribute()
    {
        _columns = GetColumnCount();
        foreach (var column in ColumnBox.Children)
        {
            column.RemoveAllChildren();
        }

        ColumnBox.RemoveAllChildren();

        var columns = new List<BoxContainer>();
        var heights = new List<int>();
        for (var i = 0; i < _columns; i++)
        {
            var column = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
                SeparationOverride = 8,
            };
            columns.Add(column);
            heights.Add(0);
            ColumnBox.AddChild(column);
        }

        foreach (var department in _departmentControls)
        {
            var shortest = heights.IndexOf(heights.Min());
            columns[shortest].AddChild(department);
            heights[shortest] += department.ChildCount + 1;
        }
    }

    private Control BuildDepartment(DepartmentPrototype department, List<JobPrototype> jobs, List<JobPrototype> shown)
    {
        var selected = jobs.Count(job => GetPriority(job.ID) != JobPriority.Never);
        var header = new PanelContainer
        {
            PanelOverride = new StyleBoxFlat(Color.InterpolateBetween(HeaderBase, department.Color, 0.45f))
            {
                ContentMarginLeftOverride = 6,
                ContentMarginRightOverride = 6,
            },
            Children =
            {
                new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    Children =
                    {
                        new Label
                        {
                            Text = Loc.GetString(department.Name),
                            HorizontalExpand = true,
                            ClipText = true,
                        },
                        new Label
                        {
                            Text = Loc.GetString("rmc-job-priorities-window-department-count",
                                ("selected", selected),
                                ("total", jobs.Count)),
                            FontColorOverride = selected > 0 ? Color.White : Color.White.WithAlpha(0.5f),
                        },
                    },
                },
            },
        };

        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
        };
        box.AddChild(header);

        for (var i = 0; i < shown.Count; i++)
        {
            box.AddChild(BuildRow(shown[i], i % 2 == 1));
        }

        return box;
    }

    private Control BuildRow(JobPrototype job, bool striped)
    {
        var priority = GetPriority(job.ID);
        var allowed = _requirements.IsAllowed(job, null, out var reason);
        var noCharacter = priority != JobPriority.Never && !HasCharacter(job.ID);

        var row = new JobRow(striped)
        {
            Disabled = !allowed,
            EnableAllKeybinds = true,
            TooltipSupplier = _ => CreateTooltip(job, priority, noCharacter, reason),
        };

        var nameColor = !allowed ? LockedColor : noCharacter ? Color.Salmon : (Color?) null;
        row.AddChild(new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 6,
            Margin = new Thickness(4, 1),
            Children =
            {
                new TextureRect
                {
                    Texture = _entity.System<SpriteSystem>().Frame0(_prototype.Index(job.Icon).Icon),
                    VerticalAlignment = VAlignment.Center,
                    Modulate = allowed ? Color.White : Color.White.WithAlpha(0.4f),
                },
                new Label
                {
                    Text = noCharacter ? $"{job.LocalizedName} !" : job.LocalizedName,
                    ClipText = true,
                    HorizontalExpand = true,
                    VAlign = Label.VAlignMode.Center,
                    FontColorOverride = nameColor,
                },
                new Label
                {
                    Text = PriorityName(priority),
                    MinWidth = PriorityWidth,
                    Align = Label.AlignMode.Right,
                    VAlign = Label.VAlignMode.Center,
                    FontColorOverride = allowed ? GetPriorityColor(priority) : LockedColor,
                },
            },
        });

        row.OnPressed += args =>
        {
            if (args.Event.Function == EngineKeyFunctions.UIClick)
                Change(job, 1);
            else if (args.Event.Function == EngineKeyFunctions.UIRightClick)
                Change(job, -1);
        };

        return row;
    }

    private static Control CreateTooltip(JobPrototype job, JobPriority priority, bool noCharacter, FormattedMessage? reason)
    {
        var message = new FormattedMessage();
        message.AddText($"{job.LocalizedName}: {PriorityName(priority)}");
        if (noCharacter)
        {
            message.PushNewline();
            message.AddMarkupPermissive(Loc.GetString("rmc-job-priorities-window-no-character"));
        }

        if (reason is { IsEmpty: false })
        {
            message.PushNewline();
            message.PushNewline();
            message.AddMessage(reason);
        }

        var tooltip = new Tooltip();
        tooltip.SetMessage(message);
        return tooltip;
    }

    private void Change(JobPrototype job, int step)
    {
        var next = (JobPriority) Math.Clamp((int) GetPriority(job.ID) + step, (int) JobPriority.Never, (int) JobPriority.High);
        if (next == GetPriority(job.ID))
            return;

        if (next == JobPriority.High)
        {
            foreach (var (other, priority) in _priorities.ToList())
            {
                if (priority == JobPriority.High && other != job.ID)
                    _priorities[other] = JobPriority.Medium;
            }
        }

        if (next == JobPriority.Never)
            _priorities.Remove(job.ID);
        else
            _priorities[job.ID] = next;

        Rebuild();
        PrioritiesChanged?.Invoke(new Dictionary<ProtoId<JobPrototype>, JobPriority>(_priorities));
    }

    private bool HasCharacter(ProtoId<JobPrototype> job)
    {
        return PlayerPreferences.IsCharacterlessJob(job, _prototype) ||
               _preferences.Preferences?.HasCharacterForJob(job) == true;
    }

    private JobPriority GetPriority(ProtoId<JobPrototype> job)
    {
        return _priorities.GetValueOrDefault(job, JobPriority.Never);
    }

    public static Color GetPriorityColor(JobPriority priority)
    {
        return priority switch
        {
            JobPriority.High => HighColor,
            JobPriority.Medium => MediumColor,
            JobPriority.Low => LowColor,
            _ => NeverColor,
        };
    }

    private static string PriorityName(JobPriority priority)
    {
        return Loc.GetString($"humanoid-profile-editor-job-priority-{priority.ToString().ToLowerInvariant()}-button");
    }

    private sealed class JobRow : ContainerButton
    {
        private static readonly StyleBoxFlat Stripe = new(Color.White.WithAlpha(0.03f));
        private static readonly StyleBoxFlat Hover = new(Color.White.WithAlpha(0.09f));
        private static readonly StyleBoxFlat Pressed = new(Color.White.WithAlpha(0.15f));
        private static readonly StyleBoxEmpty Empty = new();

        private readonly bool _striped;

        public JobRow(bool striped)
        {
            _striped = striped;
            DrawModeChanged();
        }

        protected override void DrawModeChanged()
        {
            StyleBoxOverride = DrawMode switch
            {
                DrawModeEnum.Hover => Hover,
                DrawModeEnum.Pressed => Pressed,
                _ => _striped ? Stripe : Empty,
            };
            base.DrawModeChanged();
        }
    }
}
