using Content.Client.Message;
using Content.Shared._RMC14.Power;
using Content.Shared.Materials;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._RMC14.Power;

[GenerateTypedNameReferences]
public sealed partial class RMCPortableGeneratorWindow : DefaultWindow
{
    [Dependency] private readonly IEntityManager _entityManager = default!;

    private static readonly Color GreenColor = Color.FromHex("#5AC229");
    private static readonly Color RedColor = Color.FromHex("#CE3E31");
    private static readonly Color OrangeColor = Color.FromHex("#C99A29");

    private EntityUid? _owner;
    private int _lastFuelAmount = -1;
    private bool? _lastAnchored;
    private bool? _lastGeneratorOn;

    public RMCPortableGeneratorWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void SetOwner(EntityUid owner)
    {
        _owner = owner;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_owner is not { } owner ||
            !_entityManager.TryGetComponent(owner, out RMCPortableGeneratorComponent? gen) ||
            !_entityManager.TryGetComponent(owner, out MaterialStorageComponent? storage))
            return;

        var fuelAmount = storage.Storage.GetValueOrDefault(gen.Material, 0);
        var anchored = _entityManager.TryGetComponent(owner, out TransformComponent? xform) && xform.Anchored;
        var generatorOn = gen.On;

        StatusLabel.SetMarkupPermissive((!anchored, gen.On) switch
        {
            (true, _) => $"[color={RedColor.ToHex()}]Unanchored[/color]",
            (false, true) => $"[color={GreenColor.ToHex()}]Online[/color]",
            (false, false) => $"[color={RedColor.ToHex()}]Offline[/color]",
        });

        if (fuelAmount == _lastFuelAmount && anchored == _lastAnchored && generatorOn == _lastGeneratorOn)
            return;

        _lastFuelAmount = fuelAmount;
        _lastAnchored = anchored;
        _lastGeneratorOn = generatorOn;

        var fuelSheets = fuelAmount / gen.MaterialPerSheet;
        var fuelPercent = fuelAmount % (float) gen.MaterialPerSheet / gen.MaterialPerSheet * 100;

        ToggleButton.Text = gen.On ? "Stop" : "Start";
        ToggleButton.Disabled = !anchored || fuelAmount <= 0;

        FuelLabel.SetMarkupPermissive(
            $"[color=#5B88B0]Fuel:[/color] [bold]{fuelSheets}[/bold] sheets of {gen.FuelName}");

        FuelBar.MinValue = 0;
        FuelBar.MaxValue = 100;
        FuelBar.Value = fuelPercent;
        FuelBarLabel.Text = $"{fuelPercent:F0}% of current sheet";

        EjectButton.Disabled = fuelSheets < 1;

        var watts = gen.Watts * gen.PowerGenPercent / 100;
        PowerOutputLabel.SetMarkupPermissive(
            $"[color=#5B88B0]Output:[/color] [bold]{watts} W[/bold] ({gen.PowerGenPercent}%)");

        LowerPowerButton.Disabled = gen.PowerGenPercent <= gen.MinPowerPercent;
        RaisePowerButton.Disabled = gen.PowerGenPercent >= gen.MaxPowerPercent;

        HeatBar.MaxValue = gen.OverheatThreshold;
        HeatBar.Value = Math.Min(gen.Heat, gen.OverheatThreshold);

        var heatStatus = gen.Heat switch
        {
            > 200 => $"[color={RedColor.ToHex()}]DANGER[/color]",
            >= 100 => $"[color={OrangeColor.ToHex()}]Caution[/color]",
            _ => $"[color={GreenColor.ToHex()}]Nominal[/color]",
        };

        HeatStatusLabel.SetMarkupPermissive($"[color=#5B88B0]Heat:[/color] {heatStatus}");
    }
}
