using System.Linq;
using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._RMC14.UserInterface.Crt;

/// <summary>
/// A wrapping selector whose detached popup keeps the owner's theme, including live appearance changes.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class RMCCrtOptionButton : Container, IRMCCrtThemedControl
{
    private readonly List<(int Id, string Label, RMCCrtActionButton Button)> _items = new();
    private RMCCrtThemeContext _context;

    public event Action<int>? OnItemSelected;
    public int SelectedId { get; private set; }
    public int ItemCount => _items.Count;

    public string? IconTexturePath
    {
        get => Button.IconTexturePath;
        set => Button.IconTexturePath = value;
    }

    public bool Disabled
    {
        get => Button.Disabled;
        set
        {
            Button.Disabled = value;
            if (value)
                OptionsPopup.Close();
        }
    }

    public RMCCrtOptionButton()
    {
        RobustXamlLoader.Load(this);
        RemoveChild(OptionsPopup);
        Button.Background.ScanlineOpacity = 0.08f;
        Button.OnPressed += _ => OpenPopup();
        OptionsPopup.OnPopupHide += () => OptionsPopup.Parent?.RemoveChild(OptionsPopup);
    }

    public void AddItem(string label, int? id = null)
    {
        var itemId = id ?? _items.Count;
        if (_items.Any(item => item.Id == itemId))
            throw new ArgumentException("An item with the same ID already exists.", nameof(id));

        var option = new RMCCrtActionButton
        {
            Text = label,
            TextFontSize = 10,
            Variant = RMCCrtButtonVariant.Flat,
            ContentAlignment = RMCCrtContentAlignment.Left,
            HorizontalExpand = true,
            MinHeight = 30,
        };
        option.Background.ScanlineOpacity = 0.08f;
        option.OnPressed += _ =>
        {
            SelectId(itemId);
            OptionsPopup.Close();
            OnItemSelected?.Invoke(itemId);
        };
        _items.Add((itemId, label, option));
        Options.AddChild(option);
        if (_items.Count == 1)
            SelectId(itemId);
    }

    public void SelectId(int id)
    {
        var index = _items.FindIndex(item => item.Id == id);
        if (index < 0)
            throw new ArgumentOutOfRangeException(nameof(id));

        SelectedId = id;
        Button.Text = $"{_items[index].Label}  ▾";
        foreach (var item in _items)
            item.Button.Selected = item.Id == id;
    }

    public void Clear()
    {
        OptionsPopup.Close();
        Options.DisposeAllChildren();
        _items.Clear();
        Button.Text = string.Empty;
        SelectedId = 0;
    }

    void IRMCCrtThemedControl.ApplyCrtTheme(RMCCrtThemeContext context)
    {
        _context = context;
        RMCCrtThemeHelpers.ApplyToDescendants(OptionsPopup, context);
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        ((IRMCCrtThemedControl) this).ApplyCrtTheme(RMCCrtThemeHelpers.FindContext(this));
    }

    protected override void ExitedTree()
    {
        OptionsPopup.Close();
        base.ExitedTree();
    }

    [Obsolete("Controls should only be removed from UI tree instead of being disposed")]
    protected override void Dispose(bool disposing)
    {
        if (disposing)
        {
            OptionsPopup.Close();
            OptionsPopup.Dispose();
        }
        base.Dispose(disposing);
    }

    private void OpenPopup()
    {
        if (_items.Count == 0 || Disabled)
            return;

        UserInterfaceManager.ModalRoot.AddChild(OptionsPopup);
        RMCCrtThemeHelpers.ApplyToDescendants(OptionsPopup, _context);
        Scroll.SetWidth = Width;
        Scroll.Measure(new Vector2(Width, Scroll.MaxHeight));
        OptionsPopup.Open(UIBox2.FromDimensions(GlobalPosition + new Vector2(0, Height + 1),
            new Vector2(Width, Math.Min(Scroll.DesiredSize.Y, Scroll.MaxHeight))));
    }
}
