using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.UserInterface.Crt;

/// <summary>
/// A wrapping disclosure button with an optional summary. Its contents inherit the surrounding theme.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class RMCCrtCollapsibleSection : BoxContainer
{
    private string _title = string.Empty;
    private bool _expanded;

    public event Action<bool>? OnToggled;

    public string Title
    {
        get => _title;
        set
        {
            _title = value;
            UpdateHeader();
        }
    }

    public bool Expanded
    {
        get => _expanded;
        set
        {
            if (_expanded == value)
                return;
            _expanded = value;
            Body.Visible = value;
            UpdateHeader();
            OnToggled?.Invoke(value);
        }
    }

    public RMCCrtCollapsibleSection()
    {
        RobustXamlLoader.Load(this);
        Header.Background.ScanlineOpacity = 0.08f;
        // Place the XAML header inside the button's existing padded layout.
        RemoveChild(HeaderContent);
        Header.Layout.RemoveChild(Header.TextLabel);
        Header.TextLabel.HorizontalExpand = true;
        TextColumn.AddChild(Header.TextLabel);
        Header.TextLabel.SetPositionFirst();
        Header.Layout.AddChild(HeaderContent);
        Header.OnPressed += _ => Expanded = !Expanded;
        UpdateHeader();
    }

    private void UpdateHeader()
    {
        Header.Text = Title;
        Indicator.Text = Expanded ? "▾" : "▸";
    }
}
