using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.UserInterface.Crt;

/// <summary>
/// A reusable single-line or multiline editor with length and domain validation.
/// Callers supply localized labels, validation errors, and the counter formatter.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class RMCCrtInputDialog : DefaultWindow
{
    private readonly bool _isMultiline;
    private readonly int _maxLength;

    public event Action<string>? Submitted;

    public RMCCrtInputDialog() : this(string.Empty, string.Empty, 4096)
    {
    }
    public Func<string, string?>? Validate { get; set; }
    public Func<int, int, string>? FormatCounter { get; set; }
    public string Value => _isMultiline ? Multiline.Text : Line.Text;

    public RMCCrtInputDialog(string title, string value, int maxLength, bool multiline = true)
    {
        RobustXamlLoader.Load(this);
        Title = title;
        _maxLength = maxLength;
        _isMultiline = multiline;
        MinSize = new Vector2(320, multiline ? 260 : 200);
        SetSize = new Vector2(multiline ? 540 : 420, multiline ? 330 : 200);
        Multiline.Visible = multiline;
        Line.Visible = !multiline;
        if (multiline)
        {
            Line.Parent?.RemoveChild(Line);
            Multiline.Text = value;
            Multiline.Input.OnTextChanged += _ => RefreshValidation();
        }
        else
        {
            Multiline.Parent?.RemoveChild(Multiline);
            Line.Text = value;
            Line.OnTextChanged += _ => RefreshValidation();
            Line.OnTextEntered += _ => Submit();
        }
        Save.OnPressed += _ => Submit();
        Cancel.OnPressed += _ => Close();
    }

    public void RefreshValidation()
    {
        var value = Value;
        var error = Validate?.Invoke(value);
        Save.Disabled = value.Length > _maxLength || error != null;
        Counter.Text = FormatCounter?.Invoke(value.Length, _maxLength) ?? $"{value.Length} / {_maxLength}";
        Counter.Tone = value.Length > _maxLength ? RMCCrtTone.Danger : RMCCrtTone.Muted;
        Validation.Text = error;
        Validation.Visible = error != null;
    }

    protected override void Opened()
    {
        base.Opened();
        RefreshValidation();
        if (!_isMultiline)
            Line.GrabKeyboardFocus();
        else
            Multiline.Input.GrabKeyboardFocus();
    }

    private void Submit()
    {
        RefreshValidation();
        if (Save.Disabled)
            return;

        Submitted?.Invoke(Value);
        Close();
    }
}
