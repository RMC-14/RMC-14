        Control.AddOptionCheckBox(RMCCVars.RMCPlayEmotesSkrell, RMCEmotesSkrell);

        AddMutableSounds();
    }

    private void AddMutableSounds()
    {
        var categories = _prototypes.EnumeratePrototypes<EntityPrototype>()
            .Where(p => !p.Abstract && p.TryGetComponent<RMCMutableSoundComponent>(out _, _compFactory))
            .OrderBy(p => p.Name);

        var checkBoxes = new Dictionary<string, CheckBox>();
        foreach (var category in categories)
        {
            var checkBox = new CheckBox
            {
                Text = Loc.GetString("rmc-ui-audio-sounds-play", ("sound", category.Name)),
                Margin = new Thickness(0, 0, 0, 5),
            };

            RMCMutableSounds.AddChild(checkBox);
            checkBoxes[category.ID] = checkBox;
        }

        Control.AddOption(new OptionMutedSoundsCVar(Control, _config, RMCCVars.RMCMutedSounds, checkBoxes));
    }
}
