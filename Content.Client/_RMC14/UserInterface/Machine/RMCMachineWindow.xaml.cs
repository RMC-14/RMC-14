using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RMC14.UserInterface.Machine;

[GenerateTypedNameReferences]
[Virtual]
public partial class RMCMachineWindow : BaseWindow
{
    [Dependency] private readonly IResourceCache _resourceCache = default!;

    private const float TitleBarHeight = 26;
    private const float ResizeMargin = 7;

    private readonly StyleBoxFlat _background = new(RMCMachineUiStyle.WindowColor)
    {
        BorderColor = RMCMachineUiStyle.WindowBorderColor,
        BorderThickness = new Thickness(1),
    };

    private readonly StyleBoxFlat _closeNormal = new(Color.Transparent);
    private readonly StyleBoxFlat _closeHover = new(RMCMachineUiStyle.CloseHoverColor);

    public RMCMachineWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        XamlChildren = ContentsContainer.Children;

        WindowBackground.PanelOverride = _background;
        TitleBar.PanelOverride = new StyleBoxFlat(RMCMachineUiStyle.TitleBarColor)
        {
            BorderColor = RMCMachineUiStyle.WindowBorderColor,
            BorderThickness = new Thickness(0, 0, 0, 1),
        };

        TitleLabel.FontOverride = RMCMachineUiStyle.RegularFont(_resourceCache, RMCMachineUiStyle.TitleFontSize);
        TitleLabel.FontColorOverride = RMCMachineUiStyle.TitleTextColor;

        CloseLabel.FontOverride = RMCMachineUiStyle.RegularFont(_resourceCache, RMCMachineUiStyle.CloseFontSize);
        CloseLabel.FontColorOverride = RMCMachineUiStyle.CloseTextColor;
        CloseButton.StyleBoxOverride = _closeNormal;
        CloseButton.OnMouseEntered += _ => SetCloseHovered(true);
        CloseButton.OnMouseExited += _ => SetCloseHovered(false);
        CloseButton.OnPressed += _ => Close();
    }

    public string? Title
    {
        get => TitleLabel.Text;
        set => TitleLabel.Text = value;
    }

    public Color BackgroundColor
    {
        get => _background.BackgroundColor;
        set => _background.BackgroundColor = value;
    }

    private void SetCloseHovered(bool hovered)
    {
        CloseButton.StyleBoxOverride = hovered ? _closeHover : _closeNormal;
        CloseLabel.FontColorOverride = hovered ? Color.White : RMCMachineUiStyle.CloseTextColor;
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        var mode = DragMode.None;

        if (Resizable)
        {
            if (relativeMousePos.Y < ResizeMargin)
                mode = DragMode.Top;
            else if (relativeMousePos.Y > Size.Y - ResizeMargin)
                mode = DragMode.Bottom;

            if (relativeMousePos.X < ResizeMargin)
                mode |= DragMode.Left;
            else if (relativeMousePos.X > Size.X - ResizeMargin)
                mode |= DragMode.Right;
        }

        if (mode == DragMode.None && relativeMousePos.Y < TitleBarHeight)
            mode = DragMode.Move;

        return mode;
    }
}
