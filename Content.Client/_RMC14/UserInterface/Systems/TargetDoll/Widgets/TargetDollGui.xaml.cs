using Content.Shared._RMC14.Body.Zones;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Input;

namespace Content.Client._RMC14.UserInterface.Systems.TargetDoll.Widgets;

[GenerateTypedNameReferences]
public sealed partial class TargetDollGui : UIWidget
{
    // the sprite is 32x32 and drawn at this scale, keep in sync with TextureScale in the xaml
    private const int Scale = 2;
    private const int SpriteSize = 32;

    public event Action<RMCTargetZone>? ZonePressed;

    public TargetDollGui()
    {
        RobustXamlLoader.Load(this);
    }

    protected override void KeyBindDown(GUIBoundKeyEventArgs args)
    {
        base.KeyBindDown(args);

        if (args.Function != EngineKeyFunctions.UIClick)
            return;

        // cmss13 counts pixels from 1 and from the bottom of the sprite
        var x = (int) (args.RelativePosition.X / Scale) + 1;
        var y = SpriteSize - (int) (args.RelativePosition.Y / Scale);
        if (ZoneAt(x, y) is not { } zone)
            return;

        ZonePressed?.Invoke(zone);
        args.Handle();
    }

    /// <summary>
    ///     which zone is at this pixel of the doll sprite, same regions as cmss13's zone_sel
    /// </summary>
    public static RMCTargetZone? ZoneAt(int x, int y)
    {
        switch (y)
        {
            case >= 1 and <= 3:
                return x switch
                {
                    >= 10 and <= 15 => RMCTargetZone.RightFoot,
                    >= 17 and <= 22 => RMCTargetZone.LeftFoot,
                    _ => null,
                };
            case >= 4 and <= 9:
                return x switch
                {
                    >= 10 and <= 15 => RMCTargetZone.RightLeg,
                    >= 17 and <= 22 => RMCTargetZone.LeftLeg,
                    _ => null,
                };
            case >= 10 and <= 13:
                return x switch
                {
                    >= 8 and <= 11 => RMCTargetZone.RightHand,
                    >= 12 and <= 20 => RMCTargetZone.Groin,
                    >= 21 and <= 24 => RMCTargetZone.LeftHand,
                    _ => null,
                };
            case >= 14 and <= 22:
                return x switch
                {
                    >= 8 and <= 11 => RMCTargetZone.RightArm,
                    >= 12 and <= 20 => RMCTargetZone.Chest,
                    >= 21 and <= 24 => RMCTargetZone.LeftArm,
                    _ => null,
                };
            case >= 23 and <= 30:
                if (x is < 12 or > 20)
                    return null;

                if (y is 23 or 24 && x is >= 15 and <= 17)
                    return RMCTargetZone.Mouth;

                if (y == 26 && x is >= 14 and <= 18)
                    return RMCTargetZone.Eyes;

                if (y is >= 25 and <= 27 && x is >= 15 and <= 17)
                    return RMCTargetZone.Eyes;

                return RMCTargetZone.Head;
            default:
                return null;
        }
    }
}
