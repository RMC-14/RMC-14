using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;
using static Content.Shared.Paper.PaperComponent;

namespace Content.Client._RMC14.Paper;

[GenerateTypedNameReferences]
public sealed partial class BusinessCardWindow : BaseWindow
{
    public event Action<string>? OnSaved;

    private int _maxLength = 5000;
    private static readonly Color TextColor = new(25, 25, 25);

    public int MaxInputLength
    {
        get => _maxLength;
        set
        {
            _maxLength = value;
            UpdateCharCount();
        }
    }

    public BusinessCardWindow()
    {
        RobustXamlLoader.Load(this);

        CloseButton.OnPressed += _ => Close();
        SaveButton.OnPressed += _ => Save();
        Input.OnTextChanged += _ => UpdateCharCount();
    }

    public void Populate(PaperBoundUserInterfaceState state)
    {
        var isEditing = state.Mode == PaperAction.Write;

        ContentLabel.Visible = !isEditing;
        InputContainer.Visible = isEditing;

        if (isEditing)
        {
            if (Input.TextLength == 0 && state.Text.Length > 0)
            {
                Input.TextRope = Rope.Leaf.Empty;
                Input.InsertAtCursor(state.Text);
            }
            UpdateCharCount();
        }
        else
        {
            var msg = new FormattedMessage();
            msg.AddMarkupPermissive(state.Text);
            ContentLabel.SetMessage(msg, null, TextColor);
        }
    }

    private void Save()
    {
        OnSaved?.Invoke(Rope.Collapse(Input.TextRope));
    }

    private void UpdateCharCount()
    {
        CharCount.Text = $"{Input.TextLength}/{_maxLength}";
        SaveButton.Disabled = Input.TextLength > _maxLength;
    }

    public void ClearInput()
    {
        Input.TextRope = Rope.Leaf.Empty;
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        return DragMode.Move;
    }
}
