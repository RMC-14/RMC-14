using System.Linq;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._RMC14.Admin.PayloadDeployment;

[GenerateTypedNameReferences]
public sealed partial class RMCPayloadDeploymentWindow : DefaultWindow
{
    public readonly Button PopOut = new()
    {
        Margin = new Thickness(5, 0),
        StyleClasses = { "OpenBoth" },
        Text = Loc.GetString("rmc-payload-deployment-pop-out"),
    };

    public RMCPayloadDeploymentWindow()
    {
        RobustXamlLoader.Load(this);

        if (!WindowHeader.Children.OfType<BoxContainer>().TryFirstOrDefault(out var header))
            return;

        header.AddChild(PopOut);
        PopOut.SetPositionInParent(header.ChildCount - 2);
    }
}
