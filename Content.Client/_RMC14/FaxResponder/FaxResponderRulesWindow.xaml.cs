using Content.Client.Guidebook;
using Content.Client.UserInterface.Controls;
using Content.Client.UserInterface.Systems.Guidebook;
using Content.Shared.Guidebook;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._RMC14.FaxResponder;

[GenerateTypedNameReferences]
public sealed partial class FaxResponderRulesWindow : FancyWindow
{
    [Dependency] private readonly IUserInterfaceManager _ui = default!;

    private static readonly ProtoId<GuideEntryPrototype> RulesGuide = "RMCRulesFaxResponder";
    private const float AcceptDelay = 10f;

    private float _remainingTime = AcceptDelay;

    public FaxResponderRulesWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        // Only the accept button can close this, once the timer runs out
        CloseButton.Visible = false;

        RulesLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(Loc.GetString("rmc-fax-responder-rules-text")));

        GuidebookButton.OnPressed += _ =>
            _ui.GetUIController<GuidebookUIController>().OpenGuidebook(selected: RulesGuide);
        AcceptButton.OnPressed += _ => Close();

        UpdateAcceptButton();
    }

    private void UpdateAcceptButton()
    {
        var waiting = _remainingTime > 0f;
        AcceptButton.Disabled = waiting;
        AcceptButton.Text = waiting
            ? Loc.GetString("rmc-fax-responder-rules-accept-wait", ("time", (int) MathF.Ceiling(_remainingTime)))
            : Loc.GetString("rmc-fax-responder-rules-accept");
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!AcceptButton.Disabled)
            return;

        _remainingTime = MathF.Max(0f, _remainingTime - args.DeltaSeconds);
        UpdateAcceptButton();
    }
}
