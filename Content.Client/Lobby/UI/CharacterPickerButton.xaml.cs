namespace Content.Client.Lobby.UI;

/// <summary>
/// Holds character data on the side of the setup GUI.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CharacterPickerButton : ContainerButton
{
    private IEntityManager _entManager;

    // RMC14
    private readonly ICharacterProfile _profile;
    private readonly EntProtoId _dollPrototype;
    // RMC14
    private EntityUid _previewDummy;

    /// <summary>
    /// Invoked if we should delete the attached character
    /// </summary>
    public event Action? OnDeletePressed;

    public CharacterPickerButton(
        IEntityManager entityManager,
        IPrototypeManager prototypeManager,
        ButtonGroup group,
        ICharacterProfile profile,
        bool isSelected)
    {
        RobustXamlLoader.Load(this);
        _entManager = entityManager;
        // RMC14
        _profile = profile;
        // RMC14
        AddStyleClass(StyleClassButton);
        ToggleMode = true;
        Group = group;
        var description = profile.Name;

        if (profile is not HumanoidCharacterProfile humanoid)
        {
            // RMC14
            _dollPrototype = prototypeManager.Index<SpeciesPrototype>(SharedHumanoidAppearanceSystem.DefaultSpecies).DollPrototype;
            // RMC14
        }
        else
        {
            var highPriorityJob = humanoid.JobPriorities.SingleOrDefault(p => p.Value == JobPriority.High).Key;
            if (highPriorityJob != default)
            {
                var jobName = prototypeManager.Index(highPriorityJob).LocalizedName;
                description = $"{description}\n{jobName}";
            }
        }

        Pressed = isSelected;
        DeleteButton.Visible = !isSelected;

        DescriptionLabel.Text = description;

        ConfirmDeleteButton.OnPressed += _ =>
        {
            Parent?.RemoveChild(this);
            Parent?.RemoveChild(ConfirmDeleteButton);
            OnDeletePressed?.Invoke();
        };

        DeleteButton.OnPressed += _ =>
        {
            DeleteButton.Visible = false;
            ConfirmDeleteButton.Visible = true;
        };
    }

    // RMC14
    protected override void EnteredTree()
    {
        base.EnteredTree();

        _previewDummy = _profile is HumanoidCharacterProfile humanoid
            ? UserInterfaceManager.GetUIController<LobbyUIController>().LoadProfileEntity(humanoid, null, true)
            : _entManager.Spawn(_dollPrototype, MapCoordinates.Nullspace);

        View.SetEntity(_previewDummy);
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        View.SetEntity(null);
        _entManager.DeleteEntity(_previewDummy);
        _previewDummy = default;
    }
    // RMC14
}
