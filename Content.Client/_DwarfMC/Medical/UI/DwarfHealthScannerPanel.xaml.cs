using Content.Client.Message;
using Content.Shared._DwarfMC.Medical.DwarfMed;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._DwarfMC.Medical.UI;

[GenerateTypedNameReferences]
public sealed partial class DwarfHealthScannerPanel : BoxContainer
{
    public event Action<BodyZone>? PartSelected;

    public DwarfHealthScannerPanel()
    {
        RobustXamlLoader.Load(this);

        BodyControl.PartSelected += zone => PartSelected?.Invoke(zone);
    }

    public void SetScan(IReadOnlyList<DwarfBodyPartScan> parts, IReadOnlyList<DwarfOrganScan> organs)
    {
        BodyControl.SetScan(parts, organs);
    }

    public void SetSelected(BodyZone zone)
    {
        BodyControl.SetSelected(zone);
    }

    public void PopulateStatus(
        IReadOnlyList<DwarfBodyPartScan> parts,
        IReadOnlyList<DwarfOrganScan> organs,
        BodyZone zone)
    {
        StatusContainer.DisposeAllChildren();
        StatusLabel.Visible = true;
        StatusSeparator.Visible = true;
        StatusContainer.Visible = true;
        StatusLabel.Text = $"{DwarfPartStatus.GetDisplayName(zone)} Status";

        DwarfBodyPartScan? part = null;
        foreach (var candidate in parts)
        {
            if (candidate.SlotId != zone.ToString())
                continue;

            part = candidate;
            break;
        }

        if (part is not { } scan || scan.Severed)
        {
            StatusContainer.AddChild(new Label { Text = "MISSING" });
        }
        else
        {
            StatusContainer.AddChild(new Label
            {
                Text = $"Slash: {scan.SlashDamage.Int()} / {scan.SlashThreshold.Int()}",
            });
            StatusContainer.AddChild(new Label
            {
                Text = $"Brute: {scan.BruteDamage.Int()} / {scan.BruteThreshold.Int()}",
            });
            StatusContainer.AddChild(new Label
            {
                Text = $"Burn: {scan.BurnDamage.Int()} / {scan.BurnThreshold.Int()}",
            });

            var flags = new List<string>();
            if (scan.Fractured)
                flags.Add(scan.Splinted ? "[color=#FFB833][bold]FRACTURED (SPLINTED)[/bold][/color]" : "[color=#FF7A1A][bold]FRACTURED[/bold][/color]");
            else if (scan.Splinted)
                flags.Add("SPLINTED");

            if (scan.StumpBleeding)
                flags.Add("[color=#DF3E3E]STUMP BLEEDING[/color]");

            if (scan.InternalBleeding)
                flags.Add("[color=#DF3E3E]INTERNAL BLEEDING[/color]");

            if (flags.Count > 0)
            {
                var label = new RichTextLabel();
                label.SetMarkupPermissive(string.Join(", ", flags));
                StatusContainer.AddChild(label);
            }
        }

        var hasOrgans = false;
        foreach (var organ in organs)
        {
            if (organ.Zone != zone)
                continue;

            if (!hasOrgans)
            {
                StatusContainer.AddChild(new Label
                {
                    Text = "Organs:",
                    Margin = new Thickness(0, 5, 0, 0),
                });
                hasOrgans = true;
            }

            var percent = organ.MaxDamage.Float() <= 0f
                ? 0f
                : organ.Damage.Float() / organ.MaxDamage.Float() * 100f;
            var markup = $"{organ.OrganName}: {percent:F0}%";
            if (organ.Ruptured)
                markup += " [color=#DF3E3E]RUPTURED[/color]";
            if (organ.Vital)
                markup += " [color=#FFB833]VITAL[/color]";

            var label = new RichTextLabel();
            label.SetMarkupPermissive(markup);
            StatusContainer.AddChild(label);
        }
    }
}
